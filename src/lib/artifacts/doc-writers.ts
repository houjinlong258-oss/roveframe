function docxDocumentBody(doc: DocSpec): string {
  const body: string[] = [];
  const title = (doc.title ?? '').trim();
  const subtitle = (doc.subtitle ?? '').trim();
  if (title !== '') body.push(docxParagraph(title, 'Heading1'));
  if (subtitle !== '') body.push(docxParagraph(subtitle, 'Subtitle'));

  for (const section of doc.sections ?? []) {
    const heading = (section.heading ?? '').trim();
    if (heading !== '') body.push(docxParagraph(heading, 'Heading2'));
    for (const paragraph of section.paragraphs ?? []) body.push(docxParagraph(paragraph));
    for (const bullet of section.bullets ?? []) {
      body.push(docxParagraph(`• ${bullet}`, 'ListParagraph'));
    }
    if (section.table !== undefined) body.push(docxTable(section.table));
  }

  if (body.length === 0) body.push('<w:p/>');
  return body.join('');
}

function docxDocument(doc: DocSpec): WrittenFile {
  const footer = (doc.footer ?? '').trim();
  const hasFooter = footer !== '';
  const entries: ZipEntry[] = [];

  const contentTypes = [
    XML_DECL,
    `<Types ${NS_CONTENT_TYPES}>`,
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
    '<Default Extension="xml" ContentType="application/xml"/>',
    '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>',
    '<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>',
    ...(hasFooter
      ? [
          '<Override PartName="/word/footer1.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.footer+xml"/>',
        ]
      : []),
    '</Types>',
  ].join('');
  entries.push({ name: '[Content_Types].xml', data: Buffer.from(contentTypes, 'utf8') });

  const rootRels = [
    XML_DECL,
    `<Relationships ${NS_RELATIONSHIPS}>`,
    '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>',
    '</Relationships>',
  ].join('');
  entries.push({ name: '_rels/.rels', data: Buffer.from(rootRels, 'utf8') });

  const documentRels = [
    XML_DECL,
    `<Relationships ${NS_RELATIONSHIPS}>`,
    '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>',
    ...(hasFooter
      ? [
          '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/footer" Target="footer1.xml"/>',
        ]
      : []),
    '</Relationships>',
  ].join('');
  entries.push({
    name: 'word/_rels/document.xml.rels',
    data: Buffer.from(documentRels, 'utf8'),
  });

  const sectPr =
    '<w:sectPr>' +
    (hasFooter ? '<w:footerReference w:type="default" r:id="rId2"/>' : '') +
    '<w:pgSz w:w="11906" w:h="16838"/>' +
    '<w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="708" w:footer="708" w:gutter="0"/>' +
    '</w:sectPr>';

  const document = [
    XML_DECL,
    `<w:document ${NS_WORDPROCESSING} ${NS_DOC_RELATIONSHIPS}>`,
    '<w:body>',
    docxDocumentBody(doc),
    sectPr,
    '</w:body>',
    '</w:document>',
  ].join('');
  entries.push({ name: 'word/document.xml', data: Buffer.from(document, 'utf8') });

  entries.push({ name: 'word/styles.xml', data: Buffer.from(DOCX_STYLES, 'utf8') });
  if (hasFooter) {
    entries.push({ name: 'word/footer1.xml', data: Buffer.from(docxFooterXml(footer), 'utf8') });
  }

  return written('docx', buildZip(entries));
}

