/** 0 → A、25 → Z、26 → AA。 */
function columnName(index: number): string {
  let n = index + 1;
  let out = '';
  while (n > 0) {
    const rem = (n - 1) % 26;
    out = String.fromCharCode(65 + rem) + out;
    n = Math.floor((n - 1) / 26);
  }
  return out;
}

/** Excel 工作表名不允许出现的字符：`[` `]` `:` `*` `?` `/` `\`。 */
const SHEET_NAME_INVALID_CHARS = /[[\]:*?/\\]/g;

/** 工作表名清洗：去掉 `[]:*?/\`，截断 31 字符，空名回落 SheetN，重名追加 ` (n)`。 */
function sanitizeSheetNames(sheets: TableSpec[]): string[] {
  const used = new Set<string>();
  return sheets.map((sheet, index) => {
    const raw = String(sheet.name ?? '').replace(SHEET_NAME_INVALID_CHARS, '').trim();
    const base = raw.length > 31 ? raw.slice(0, 31) : raw;
    const seed = base.length > 0 ? base : `Sheet${index + 1}`;
    let name = seed;
    let counter = 2;
    while (used.has(name.toLowerCase())) {
      const suffix = ` (${counter})`;
      name = `${seed.slice(0, Math.max(1, 31 - suffix.length))}${suffix}`;
      counter += 1;
    }
    used.add(name.toLowerCase());
    return name;
  });
}

function xlsxCell(ref: string, value: CellValue, styleIndex: number): string {
  const style = styleIndex > 0 ? ` s="${styleIndex}"` : '';
  if (value === null || value === '') return `<c r="${ref}"${style}/>`;
  if (typeof value === 'number') {
    return Number.isFinite(value)
      ? `<c r="${ref}"${style}><v>${value}</v></c>`
      : `<c r="${ref}" t="inlineStr"${style}><is><t xml:space="preserve">${escapeXml(String(value))}</t></is></c>`;
  }
  if (typeof value === 'boolean') {
    return `<c r="${ref}" t="b"${style}><v>${value ? 1 : 0}</v></c>`;
  }
  return `<c r="${ref}" t="inlineStr"${style}><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`;
}

function xlsxSheetXml(sheet: TableSpec): string {
  const { columns, rows } = tableShape(sheet);
  const colCount = columns.length;
  const out: string[] = [XML_DECL];
  out.push(`<worksheet ${NS_SPREADSHEET}>`);
  const lastRow = Math.max(1, rows.length + (colCount > 0 ? 1 : 0));
  out.push(`<dimension ref="A1:${columnName(Math.max(0, colCount - 1))}${lastRow}"/>`);
  out.push('<sheetViews><sheetView workbookViewId="0"/></sheetViews>');
  out.push('<sheetFormatPr defaultRowHeight="15"/>');
  out.push('<sheetData>');
  if (colCount > 0) {
    const header = columns.map((column, i) => xlsxCell(`${columnName(i)}1`, column, 1)).join('');
    out.push(`<row r="1">${header}</row>`);
  }
  rows.forEach((row, index) => {
    const rowNumber = index + (colCount > 0 ? 2 : 1);
    const cells = columns
      .map((_, i) => xlsxCell(`${columnName(i)}${rowNumber}`, row[i] ?? null, 0))
      .join('');
    out.push(`<row r="${rowNumber}">${cells}</row>`);
  });
  out.push('</sheetData>');
  out.push('</worksheet>');
  return out.join('');
}

