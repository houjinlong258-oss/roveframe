/** RFC4180 字段转义：含逗号 / 双引号 / 换行的字段用双引号包裹，内部 `"` → `""`。 */
function csvField(value: string): string {
  return /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

function csvRow(values: string[]): string {
  return values.map(csvField).join(',');
}

/**
 * CSV 文本（不含 BOM，调用方负责加 `\uFEFF`）。
 * 行分隔符用 RFC4180 规定的 CRLF；多表时用空行分隔，并在每张表前加 `# <name>` 注释行。
 */
function csvText(sheets: TableSpec[], title?: string): string {
  const lines: string[] = [];
  const trimmedTitle = title === undefined ? '' : oneLine(title).trim();
  if (trimmedTitle !== '') lines.push(`# ${trimmedTitle}`);

  const multi = sheets.length > 1;
  sheets.forEach((sheet, index) => {
    const { columns, rows } = tableShape(sheet);
    if (index > 0) lines.push('');
    if (multi) lines.push(`# ${oneLine(sheet.name)}`);
    lines.push(csvRow(columns));
    for (const row of rows) {
      lines.push(csvRow(columns.map((_, i) => cellText(row[i] ?? null))));
    }
  });

  return `${lines.join('\r\n')}\r\n`;
}

