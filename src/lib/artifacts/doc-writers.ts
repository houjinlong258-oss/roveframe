function htmlShell(options: { title: string; bodyBlocks: string[]; footer?: string }): string {
  const footer = (options.footer ?? '').trim();
  const body = [...options.bodyBlocks];
  if (footer !== '') body.push(`<footer class="doc-footer">${escapeHtml(footer)}</footer>`);
  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1" />',
    `<title>${escapeHtml(options.title)}</title>`,
    '<style>',
    HTML_STYLE,
    '</style>',
    '</head>',
    '<body>',
    '<main class="page">',
    ...body,
    '</main>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
}

function htmlTable(sheet: TableSpec, headingLevel: 2 | 3): string {
  const { columns, rows } = tableShape(sheet);
  const head = `<thead><tr>${columns
    .map((column) => `<th scope="col">${htmlCell(column)}</th>`)
    .join('')}</tr></thead>`;
  const bodyRows = rows
    .map(
      (row) =>
        `<tr>${columns
          .map((_, i) => `<td>${htmlCell(cellText(row[i] ?? null))}</td>`)
          .join('')}</tr>`,
    )
    .join('');
  const name = sheet.name.trim();
  const caption = name === '' ? '' : `<h${headingLevel}>${escapeHtml(name)}</h${headingLevel}>`;
  const table = `<table>${head}<tbody>${bodyRows}</tbody></table>`;
  return `<section class="sheet">${caption}${table}</section>`;
}

function htmlTables(sheets: TableSpec[], title?: string): string {
  const trimmedTitle = (title ?? '').trim();
  const blocks: string[] = [];
  if (trimmedTitle !== '') blocks.push(`<h1>${escapeHtml(trimmedTitle)}</h1>`);
  if (sheets.length === 0) blocks.push('<p class="empty">No data.</p>');
  for (const sheet of sheets) blocks.push(htmlTable(sheet, 2));
  const fallbackTitle = trimmedTitle !== '' ? trimmedTitle : (sheets[0]?.name ?? 'Table export');
  return htmlShell({ title: fallbackTitle, bodyBlocks: blocks });
}

function htmlDocument(doc: DocSpec): string {
  const blocks: string[] = [];
  const title = (doc.title ?? '').trim();
  const subtitle = (doc.subtitle ?? '').trim();
  if (title !== '') blocks.push(`<h1>${escapeHtml(title)}</h1>`);
  if (subtitle !== '') blocks.push(`<p class="doc-subtitle">${escapeHtml(subtitle)}</p>`);

  for (const section of doc.sections ?? []) {
    const heading = (section.heading ?? '').trim();
    if (heading !== '') blocks.push(`<h2>${escapeHtml(heading)}</h2>`);
    for (const paragraph of section.paragraphs ?? []) {
      blocks.push(`<p>${htmlCell(paragraph)}</p>`);
    }
    const bullets = section.bullets ?? [];
    if (bullets.length > 0) {
      blocks.push(`<ul>${bullets.map((b) => `<li>${htmlCell(b)}</li>`).join('')}</ul>`);
    }
    if (section.table !== undefined) blocks.push(htmlTable(section.table, 3));
  }

  if (blocks.length === 0) blocks.push('<p class="empty">Empty document.</p>');
  const shellTitle = title !== '' ? title : 'Document';
  return htmlShell({ title: shellTitle, bodyBlocks: blocks, footer: doc.footer });
}

