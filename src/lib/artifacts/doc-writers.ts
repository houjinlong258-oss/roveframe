function docxRun(text: string, bold = false): string {
  if (text === '') return '';
  const rPr = bold ? '<w:rPr><w:b/></w:rPr>' : '';
  return `<w:r>${rPr}<w:t xml:space="preserve">${escapeXml(text)}</w:t></w:r>`;
}

function docxParagraph(text: string, styleId?: string): string {
  const run = docxRun(text);
  if (run === '') return '<w:p/>';
  const pPr = styleId === undefined ? '' : `<w:pPr><w:pStyle w:val="${styleId}"/></w:pPr>`;
  return `<w:p>${pPr}${run}</w:p>`;
}

function docxTableRow(cells: string[], header: boolean): string {
  const trPr = header ? '<w:trPr><w:tblHeader/></w:trPr>' : '';
  const tcs = cells
    .map((text) => {
      const run = docxRun(text, header);
      const paragraph = run === '' ? '<w:p/>' : `<w:p>${run}</w:p>`;
      return `<w:tc><w:tcPr><w:tcW w:w="0" w:type="auto"/></w:tcPr>${paragraph}</w:tc>`;
    })
    .join('');
  return `<w:tr>${trPr}${tcs}</w:tr>`;
}

function docxTable(sheet: TableSpec): string {
  const { columns, rows: bodyRows } = tableShape(sheet);
  const borders =
    '<w:tblBorders>' +
    ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']
      .map((side) => `<w:${side} w:val="single" w:sz="4" w:space="0" w:color="CBD2D9"/>`)
      .join('') +
    '</w:tblBorders>';
  const grid = columns.map(() => '<w:gridCol w:w="2400"/>').join('');
  const rows: string[] = [];
  if (columns.length > 0) rows.push(docxTableRow(columns.map((c) => c), true));
  for (const row of bodyRows) {
    rows.push(docxTableRow(columns.map((_, i) => cellText(row[i] ?? null)), false));
  }
  return (
    '<w:tbl>' +
    `<w:tblPr><w:tblW w:w="0" w:type="auto"/>${borders}<w:tblLayout w:type="autofit"/></w:tblPr>` +
    `<w:tblGrid>${grid}</w:tblGrid>` +
    rows.join('') +
    '</w:tbl>' +
    '<w:p/>'
  );
}

