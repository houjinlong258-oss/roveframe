/**
 * 零依赖文档 / 表格序列化器（artifact writers）。
 *
 * 用途：AI COO 的「产物导出」链路 —— 把结构化的表格（TableSpec）与文档（DocSpec）
 * 序列化成可直接下载 / 落盘的字节流（WrittenFile：data + mime + ext）。
 * 本模块**只依赖 Node.js 内置模块**（node:zlib + Buffer），不引入任何第三方依赖，
 * 因此可以在 API 路由、脚本、测试中被安全复用。
 *
 * 能力矩阵：
 * - writeTable   ：csv（UTF-8 BOM + RFC4180 转义）/ xlsx（真实 OOXML，ZIP 包）/ md / html / json
 * - writeDocument：docx（真实 OOXML，ZIP 包）/ md / txt / html / json
 * - 不支持的组合一律抛出 Error（例如 writeTable('docx') / writeDocument('csv')）。
 *
 * 实现要点：
 * - 私有 buildZip：最小 ZIP writer（deflateRaw，compression method 8），CRC-32 用自实现查表算法；
 *   写入 Local File Header + Central Directory + EOCD，文件名 UTF-8 且 general purpose flag = 0x0800；
 *   时间戳固定（1980-01-01 00:00），因此同样输入**输出字节完全确定**，可直接被单测严格断言。
 * - xlsx：inlineStr 内联字符串（不生成 sharedStrings.xml），数字写数值单元格，布尔写 t="b"，
 *   表头复用 styles.xml 里的加粗字体（s="1"）；工作表名清洗 `[]:*?/\`、截断 31 字符并去重。
 * - docx：标题 / 小节标题通过 w:pStyle 引用 styles.xml 中的 Heading1 / Heading2；
 *   列表用 ListParagraph 段落 + “• ” 文本前缀（**有意不引入 numbering.xml**，避免复杂依赖链）；
 *   表格是真实的 w:tbl（内联 tblBorders）；页脚（footer）写成独立的 word/footer1.xml 部件 + sectPr 引用。
 * - html：完整、自包含、内联 CSS、A4 友好（@page + 打印媒体查询），无任何外部资源，可直接浏览器打开并「打印成 PDF」。
 *
 * 有意为之的简化（不是 bug）：
 * - xlsx 只有一个加粗表头样式，不写主题 / 数字格式 / 列宽 / 冻结窗格；正文单元格全部为 inlineStr 或数值；
 * - docx 不支持富文本（粗体/斜体行内标记）、图片、目录；
 * - 表格宽度以 columns 定义为唯一口径：多出的行值被忽略，缺失的补空单元格（对全部格式一致）。
 */

import { deflateRawSync } from 'node:zlib';

/* -------------------------------------------------------------------------- */
/* 公共类型                                                                    */
/* -------------------------------------------------------------------------- */

export type ArtifactFormat = 'csv' | 'xlsx' | 'docx' | 'md' | 'txt' | 'json' | 'html';

export interface TableSpec {
  /** 工作表名（xlsx）/ 表标题（md/html） */
  name: string;
  columns: string[];
  rows: Array<Array<string | number | boolean | null>>;
}

export interface DocSection {
  heading?: string;
  paragraphs?: string[];
  bullets?: string[];
  table?: TableSpec;
}

export interface DocSpec {
  title?: string;
  subtitle?: string;
  sections: DocSection[];
  /** 页脚署名，如 "Generated by RoveFrame AI COO" */
  footer?: string;
}

export interface WrittenFile {
  data: Buffer;
  mime: string;
  ext: string;
}

type CellValue = string | number | boolean | null;

const TABLE_FORMATS: readonly ArtifactFormat[] = ['csv', 'xlsx', 'md', 'html', 'json'];
const DOCUMENT_FORMATS: readonly ArtifactFormat[] = ['docx', 'md', 'txt', 'html', 'json'];

const FORMAT_META: Record<ArtifactFormat, { mime: string; ext: string }> = {
  csv: { mime: 'text/csv; charset=utf-8', ext: 'csv' },
  xlsx: {
    mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    ext: 'xlsx',
  },
  docx: {
    mime: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    ext: 'docx',
  },
  md: { mime: 'text/markdown; charset=utf-8', ext: 'md' },
  txt: { mime: 'text/plain; charset=utf-8', ext: 'txt' },
  json: { mime: 'application/json; charset=utf-8', ext: 'json' },
  html: { mime: 'text/html; charset=utf-8', ext: 'html' },
};

function written(format: ArtifactFormat, data: Buffer): WrittenFile {
  const meta = FORMAT_META[format];
  return { data, mime: meta.mime, ext: meta.ext };
}

function unsupported(format: ArtifactFormat, api: string, allowed: readonly ArtifactFormat[]): never {
  throw new Error(
    `${api}: 不支持的格式 "${String(format)}"（支持：${allowed.join(' / ')}）`,
  );
}

