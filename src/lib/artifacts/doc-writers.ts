/* 纯文本（txt）                                                               */
/* -------------------------------------------------------------------------- */

function txtTable(sheet: TableSpec): string {
  const { columns, rows } = tableShape(sheet);
  const header = columns.map(cellText);
  const body = rows.map((row) => columns.map((_, i) => cellText(row[i] ?? null)));
  const separator = columns
    .map((column) => '-'.repeat(Math.max(3, column.length)))
    .join('-+-');
  const lines = [header.join(' | '), separator, ...body.map((cells) => cells.join(' | '))];
  return lines.join('\n');
}

function textDocument(doc: DocSpec): string {
  const blocks: string[] = [];
  const title = (doc.title ?? '').trim();
  const subtitle = (doc.subtitle ?? '').trim();
  if (title !== '') {
    blocks.push(`${title}\n${'='.repeat(Math.max(1, title.length))}`);
  }
  if (subtitle !== '') blocks.push(subtitle);

  for (const section of doc.sections ?? []) {
    const parts: string[] = [];
    const heading = (section.heading ?? '').trim();
    if (heading !== '') parts.push(`${heading}\n${'-'.repeat(Math.max(1, heading.length))}`);
    for (const paragraph of section.paragraphs ?? []) parts.push(paragraph);
    const bullets = section.bullets ?? [];
    if (bullets.length > 0) parts.push(bullets.map((b) => `• ${b}`).join('\n'));
    if (section.table !== undefined) {
      const block: string[] = [];
      const tableName = section.table.name.trim();
      if (tableName !== '') block.push(`[${tableName}]`);
      block.push(txtTable(section.table));
      parts.push(block.join('\n'));
    }
    if (parts.length > 0) blocks.push(parts.join('\n\n'));
  }

  const footer = (doc.footer ?? '').trim();
  if (footer !== '') blocks.push(`${'-'.repeat(40)}\n${footer}`);

  return blocks.length === 0 ? '' : `${blocks.join('\n\n')}\n`;
}

