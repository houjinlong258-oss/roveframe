/** markdown 单元格：转义 `|`，换行折叠为 `<br>`。 */
function mdCell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r\n|\r|\n/g, '<br>');
}

function mdTable(sheet: TableSpec): string {
  const { columns, rows } = tableShape(sheet);
  const lines: string[] = [];
  lines.push(`| ${columns.map(mdCell).join(' | ')} |`);
  lines.push(`| ${columns.map(() => '---').join(' | ')} |`);
  for (const row of rows) {
    const cells = columns.map((_, i) => mdCell(cellText(row[i] ?? null)));
    lines.push(`| ${cells.join(' | ')} |`);
  }
  return lines.join('\n');
}

function markdownTables(sheets: TableSpec[], title?: string): string {
  const blocks: string[] = [];
  const trimmedTitle = title === undefined ? '' : title.trim();
  if (trimmedTitle !== '') blocks.push(`# ${mdCell(trimmedTitle)}`);
  for (const sheet of sheets) {
    const parts: string[] = [];
    const name = sheet.name.trim();
    if (name !== '') parts.push(`## ${mdCell(name)}`);
    parts.push(mdTable(sheet));
    blocks.push(parts.join('\n\n'));
  }
  return blocks.length === 0 ? '' : `${blocks.join('\n\n')}\n`;
}

function markdownDocument(doc: DocSpec): string {
  const blocks: string[] = [];
  const title = (doc.title ?? '').trim();
  const subtitle = (doc.subtitle ?? '').trim();
  if (title !== '') blocks.push(`# ${mdCell(title)}`);
  if (subtitle !== '') blocks.push(`*${mdCell(subtitle)}*`);

  for (const section of doc.sections ?? []) {
    const parts: string[] = [];
    const heading = (section.heading ?? '').trim();
    if (heading !== '') parts.push(`## ${mdCell(heading)}`);
    for (const paragraph of section.paragraphs ?? []) parts.push(mdCell(paragraph));
    const bullets = section.bullets ?? [];
    if (bullets.length > 0) parts.push(bullets.map((b) => `- ${mdCell(b)}`).join('\n'));
    if (section.table !== undefined) {
      const block: string[] = [];
      const tableName = section.table.name.trim();
      if (tableName !== '') block.push(`**${mdCell(tableName)}**`);
      block.push(mdTable(section.table));
      parts.push(block.join('\n\n'));
    }
    if (parts.length > 0) blocks.push(parts.join('\n\n'));
  }

  const footer = (doc.footer ?? '').trim();
  if (footer !== '') blocks.push(`---\n\n${mdCell(footer)}`);

  return blocks.length === 0 ? '' : `${blocks.join('\n\n')}\n`;
}

