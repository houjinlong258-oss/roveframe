function xlsxWorkbook(sheets: TableSpec[]): WrittenFile {
  if (sheets.length === 0) {
    throw new Error('writeTable: xlsx 至少需要一张工作表（sheets 不能为空）');
  }
  const names = sanitizeSheetNames(sheets);
  const entries: ZipEntry[] = [];

  const contentTypes = [
    XML_DECL,
    `<Types ${NS_CONTENT_TYPES}>`,
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
    '<Default Extension="xml" ContentType="application/xml"/>',
    '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>',
    '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>',
    ...sheets.map(
      (_, i) =>
        `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`,
    ),
    '</Types>',
  ].join('');
  entries.push({ name: '[Content_Types].xml', data: Buffer.from(contentTypes, 'utf8') });

  const rootRels = [
    XML_DECL,
    `<Relationships ${NS_RELATIONSHIPS}>`,
    `<Relationship Id="rId1" Type="${REL_NS}/officeDocument" Target="xl/workbook.xml"/>`,
    '</Relationships>',
  ].join('');
  entries.push({ name: '_rels/.rels', data: Buffer.from(rootRels, 'utf8') });

  const workbook = [
    XML_DECL,
    `<workbook ${NS_SPREADSHEET} ${NS_DOC_RELATIONSHIPS}>`,
    '<bookViews><workbookView xWindow="0" yWindow="0" windowWidth="20000" windowHeight="12000"/></bookViews>',
    '<sheets>',
    ...names.map(
      (name, i) => `<sheet name="${escapeXml(name)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`,
    ),
    '</sheets>',
    '</workbook>',
  ].join('');
  entries.push({ name: 'xl/workbook.xml', data: Buffer.from(workbook, 'utf8') });

  const workbookRels = [
    XML_DECL,
    `<Relationships ${NS_RELATIONSHIPS}>`,
    ...sheets.map(
      (_, i) =>
        `<Relationship Id="rId${i + 1}" Type="${REL_NS}/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`,
    ),
    `<Relationship Id="rId${sheets.length + 1}" Type="${REL_NS}/styles" Target="styles.xml"/>`,
    '</Relationships>',
  ].join('');
  entries.push({ name: 'xl/_rels/workbook.xml.rels', data: Buffer.from(workbookRels, 'utf8') });

  sheets.forEach((sheet, i) => {
    entries.push({
      name: `xl/worksheets/sheet${i + 1}.xml`,
      data: Buffer.from(xlsxSheetXml(sheet), 'utf8'),
    });
  });

  entries.push({ name: 'xl/styles.xml', data: Buffer.from(XLSX_STYLES, 'utf8') });

  return written('xlsx', buildZip(entries));
}

