/** 表格类产物：csv / xlsx / md / html / json 支持；其他格式抛错。 */
export function writeTable(
  format: ArtifactFormat,
  sheets: TableSpec[],
  spec?: { title?: string },
): WrittenFile {
  const list = sheets ?? [];
  switch (format) {
    case 'csv':
      return written('csv', Buffer.from(`\uFEFF${csvText(list, spec?.title)}`, 'utf8'));
    case 'json':
      return written('json', Buffer.from(JSON.stringify(list, null, 2), 'utf8'));
    case 'md':
      return written('md', Buffer.from(markdownTables(list, spec?.title), 'utf8'));
    case 'html':
      return written('html', Buffer.from(htmlTables(list, spec?.title), 'utf8'));
    case 'xlsx':
      return xlsxWorkbook(list);
    default:
      return unsupported(format, 'writeTable', TABLE_FORMATS);
  }
}

/** 文档类产物：docx / md / txt / html / json 支持；其他格式抛错。 */
export function writeDocument(format: ArtifactFormat, doc: DocSpec): WrittenFile {
  switch (format) {
    case 'json':
      return written('json', Buffer.from(JSON.stringify(doc, null, 2), 'utf8'));
    case 'md':
      return written('md', Buffer.from(markdownDocument(doc), 'utf8'));
    case 'txt':
      return written('txt', Buffer.from(textDocument(doc), 'utf8'));
    case 'html':
      return written('html', Buffer.from(htmlDocument(doc), 'utf8'));
    case 'docx':
      return docxDocument(doc);
    default:
      return unsupported(format, 'writeDocument', DOCUMENT_FORMATS);
  }
}
