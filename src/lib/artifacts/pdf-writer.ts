/**
 * 子集里保留的表（PDF 只需要这些）：
 * - glyf / loca 重建，head / maxp 就地改写，post 裁成 v3.0；
 * - cmap 原样保留（gid 不重映射，映射依旧有效），hmtx / hhea 原样保留（读到的宽度一定在表内）；
 * - 保留 cvt / fpgm / prep：体积很小，但能让查看器继续做 hinting，避免栅格化差异；
 * - kern / GPOS / GSUB / GDEF / gasp / hdmx / LTSH / VDMX 等全部丢弃（PDF 里由 Tm 自己排版，用不到）。
 */
const SUBSET_KEEP_TABLES: readonly string[] = [
  'OS/2',
  'cmap',
  'cvt ',
  'fpgm',
  'glyf',
  'head',
  'hhea',
  'hmtx',
  'loca',
  'maxp',
  'name',
  'post',
  'prep',
];

/* 复合字形 component 的 flag（OpenType glyf 规范） */
const COMPONENT_ARG_1_AND_2_ARE_WORDS = 0x0001;
const COMPONENT_WE_HAVE_A_SCALE = 0x0008;
const COMPONENT_MORE_COMPONENTS = 0x0020;
const COMPONENT_WE_HAVE_AN_X_AND_Y_SCALE = 0x0040;
const COMPONENT_WE_HAVE_A_TWO_BY_TWO = 0x0080;

/** loca 表 → numGlyphs + 1 个 glyf 偏移。表长不足直接抛错（交给上层回退）。 */
function readLoca(loca: Buffer, numGlyphs: number, indexToLocFormat: number): number[] {
  const entrySize = indexToLocFormat === 0 ? 2 : 4;
  if (loca.length < (numGlyphs + 1) * entrySize) throw new Error('loca 表长度不足');
  const offsets: number[] = [];
  for (let gid = 0; gid <= numGlyphs; gid += 1) {
    offsets.push(indexToLocFormat === 0 ? u16(loca, gid * 2) * 2 : u32(loca, gid * 4));
  }
  return offsets;
}

/**
 * 复合字形（numberOfContours < 0）引用的组件 gid 列表。
 * 每个 component 是「flags(2) + glyphIndex(2) + args + 可选变换」，args 与变换的长度由 flag 决定；
 * ARGS_ARE_XY_VALUES 只影响参数语义、不影响长度，WE_HAVE_INSTRUCTIONS 只影响最后一个 component
 * 之后的附加数据，所以这里按 flag 累加长度直到 MORE_COMPONENTS 清零即可。
 */
function compositeGlyphComponents(glyf: Buffer, start: number, end: number): number[] {
  const components: number[] = [];
  let offset = start + 10; // numberOfContours(2) + xMin/yMin/xMax/yMax(8)
  while (offset + 4 <= end) {
    const flags = u16(glyf, offset);
    components.push(u16(glyf, offset + 2));
    offset += 4;
    offset += (flags & COMPONENT_ARG_1_AND_2_ARE_WORDS) !== 0 ? 4 : 2;
    if ((flags & COMPONENT_WE_HAVE_A_SCALE) !== 0) offset += 2;
    else if ((flags & COMPONENT_WE_HAVE_AN_X_AND_Y_SCALE) !== 0) offset += 4;
    else if ((flags & COMPONENT_WE_HAVE_A_TWO_BY_TWO) !== 0) offset += 8;
    if ((flags & COMPONENT_MORE_COMPONENTS) === 0) break;
  }
  return components;
}

/** post 表裁剪成 version 3.0 的 32 字节最小表（无字形名），保留斜体角 / 下划线度量。 */
function minimalPostTable(post: Buffer | null): Buffer {
  const out = Buffer.alloc(32);
  out.writeUInt32BE(0x00030000, 0);
  if (post !== null && post.length >= 16) post.copy(out, 4, 4, 16);
  return out;
}

/**
 * 生成字体子集：只保留用到的字形 + 复合组件闭包，重建 glyf / loca / sfont 表目录。
 * gid 保持不变（不做重映射），保留 0..maxUsedGid 的槽位，未用到的槽写零长度空字形。
 * 任何异常都向上抛，由 writePdf 回退成整份字体嵌入。
 */
function subsetFontProgram(program: Buffer, usedGids: Set<number>): { program: Buffer; stats: SubsetStats } {
  const tables = readTableDirectory(program, 0);
  const head = tableData(program, tables, 'head');
  const maxp = tableData(program, tables, 'maxp');
  const hhea = tableData(program, tables, 'hhea');
  const hmtx = tableData(program, tables, 'hmtx');
  const cmap = tableData(program, tables, 'cmap');
  const loca = tableData(program, tables, 'loca');
  const glyf = tableData(program, tables, 'glyf');
  if (head === null || head.length < 54) throw new Error('head 表缺失或过短');
  if (maxp === null || maxp.length < 6) throw new Error('maxp 表缺失或过短');
  if (hhea === null || hmtx === null || cmap === null) throw new Error('hhea / hmtx / cmap 表缺失');
  if (loca === null || glyf === null) throw new Error('glyf / loca 表缺失');

  const numGlyphs = u16(maxp, 4);
  const indexToLocFormat = i16(head, 50);
  if (numGlyphs <= 0 || (indexToLocFormat !== 0 && indexToLocFormat !== 1)) {
    throw new Error('head / maxp 字段异常');
  }
  const offsets = readLoca(loca, numGlyphs, indexToLocFormat);

  // ① 用到的 gid + .notdef，再做复合组件递归闭包
  const kept = new Set<number>();
  const pending: number[] = [0];
  for (const gid of usedGids) {
    if (gid >= 0 && gid < numGlyphs) pending.push(gid);
  }
  while (pending.length > 0) {
    const gid = pending.pop();
    if (gid === undefined) break;
    if (kept.has(gid)) continue;
    kept.add(gid);
    const start = offsets[gid];
    if (start > glyf.length) throw new Error(`glyf 偏移越界（gid ${gid}）`);
    const end = Math.min(offsets[gid + 1], glyf.length);
    if (end < start) throw new Error(`glyf 区间非法（gid ${gid}）`);
    if (end > start && i16(glyf, start) < 0) {
      for (const component of compositeGlyphComponents(glyf, start, end)) {
        if (component >= 0 && component < numGlyphs && !kept.has(component)) pending.push(component);
      }
    }
  }

  let maxUsedGid = 0;
  for (const gid of kept) maxUsedGid = Math.max(maxUsedGid, gid);
  const newGlyphCount = maxUsedGid + 1;

  // ② 重建 glyf：每个字形 4 字节对齐（short loca 只要求偶数），未用到的槽是零长度空字形
  const glyphChunks: Buffer[] = [];
  const newOffsets: number[] = [];
  let glyfLength = 0;
  for (let gid = 0; gid < newGlyphCount; gid += 1) {
    newOffsets.push(glyfLength);
    if (!kept.has(gid)) continue;
    const start = offsets[gid];
    const end = Math.min(offsets[gid + 1], glyf.length);
    if (end <= start) continue;
    let data = Buffer.from(glyf.subarray(start, end));
    const padding = (4 - (data.length % 4)) % 4;
    if (padding > 0) data = Buffer.concat([data, Buffer.alloc(padding)]);
    glyphChunks.push(data);
    glyfLength += data.length;
  }
  newOffsets.push(glyfLength);
  const newGlyf = Buffer.concat(glyphChunks, glyfLength);

  // ③ 重建 loca：short 只能表示 offset / 2，所以总长必须 <= 0xFFFF * 2
  const useShortLoca = glyfLength <= 0xffff * 2;
  const newLoca = Buffer.alloc((newGlyphCount + 1) * (useShortLoca ? 2 : 4));
  for (const [index, offset] of newOffsets.entries()) {
    if (useShortLoca) newLoca.writeUInt16BE(offset / 2, index * 2);
    else newLoca.writeUInt32BE(offset, index * 4);
  }

  const newHead = Buffer.from(head);
  newHead.writeInt16BE(useShortLoca ? 0 : 1, 50);
  const newMaxp = Buffer.from(maxp);
  newMaxp.writeUInt16BE(newGlyphCount, 4);

  const subsetTables: SfntTable[] = [];
  for (const tag of SUBSET_KEEP_TABLES) {
    if (tag === 'glyf') subsetTables.push({ tag, data: newGlyf });
    else if (tag === 'loca') subsetTables.push({ tag, data: newLoca });
    else if (tag === 'head') subsetTables.push({ tag, data: newHead });
    else if (tag === 'maxp') subsetTables.push({ tag, data: newMaxp });
    else if (tag === 'post') subsetTables.push({ tag, data: minimalPostTable(tableData(program, tables, 'post')) });
    else {
      const data = tableData(program, tables, tag);
      if (data !== null) subsetTables.push({ tag, data });
    }
  }

  const subsetProgram = buildSfnt(SFNT_VERSION_1, subsetTables);
  return {
    program: subsetProgram,
    stats: {
      glyphsTotal: numGlyphs,
      glyphsKept: kept.size,
      fontBytesBefore: program.length,
      fontBytesAfter: subsetProgram.length,
    },
  };
}

/** FontFile2 的 FlateDecode 结果：整份字体程序走缓存（十几 MB，压一次就够），子集程序现压（很小）。 */
function compressedFontProgram(font: EmbeddedFont, program: Buffer): Buffer {
  if (program === font.program) {
    if (font.programCompressed === undefined) font.programCompressed = deflateSync(program);
    return font.programCompressed;
  }
  return deflateSync(program);
}

