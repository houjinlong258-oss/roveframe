/** 码点是否落在可打印区间。 */
function isPrintableAscii(codePoint: number): boolean {
  return codePoint >= 0x20 && codePoint <= 0x7e;
}

function isLatin1(codePoint: number): boolean {
  return codePoint >= 0xa0 && codePoint <= 0xff;
}

/** Unicode 码点 → WinAnsi 字节；无法表示时回落 `?`。 */
function winAnsiByte(codePoint: number): number {
  if (codePoint === 0x09 || codePoint === 0x0a || codePoint === 0x0d) return 0x20;
  if (isPrintableAscii(codePoint) || isLatin1(codePoint)) return codePoint;
  return WIN_ANSI_HIGH.get(codePoint) ?? 0x3f;
}

/**
 * 内容里是否有 base14 Helvetica 无法表示的字符（CJK、emoji、重音外的符号等）。
 * 判据是「码点在 Latin-1 / WinAnsi 之外」：C0 控制字符（< 0x20）与 DEL 属于 ASCII 区，
 * 排版时会被折成空格或 `?` 清掉，不算「缺字体」，因此不触发降级标记。
 */
export function needsUnicodeFont(text: string): boolean {
  for (const ch of String(text ?? '')) {
    const codePoint = ch.codePointAt(0) ?? 0;
    if (codePoint < 0x80) continue;
    if (isLatin1(codePoint)) continue;
    if (WIN_ANSI_HIGH.has(codePoint)) continue;
    return true;
  }
  return false;
}

function base14Width(codePoint: number, bold: boolean): number {
  if (codePoint >= 32 && codePoint <= 126) {
    const table = bold ? HELVETICA_BOLD_WIDTHS : HELVETICA_WIDTHS;
    return table[codePoint - 32];
  }
  return bold ? HELVETICA_BOLD_DEFAULT_WIDTH : HELVETICA_DEFAULT_WIDTH;
}

/** Helvetica 的 /Widths（FirstChar 32、LastChar 255）。 */
function base14WidthArray(bold: boolean): string {
  const table = bold ? HELVETICA_BOLD_WIDTHS : HELVETICA_WIDTHS;
  const fallback = bold ? HELVETICA_BOLD_DEFAULT_WIDTH : HELVETICA_DEFAULT_WIDTH;
  const widths: number[] = [];
  for (let codePoint = 32; codePoint <= 255; codePoint += 1) {
    widths.push(codePoint <= 126 ? table[codePoint - 32] : fallback);
  }
  return `[ ${widths.join(' ')} ]`;
}

