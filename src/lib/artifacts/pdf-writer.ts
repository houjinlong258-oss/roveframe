function readTableTag(buffer: Buffer, offset: number): string {
  return buffer.toString('latin1', offset, offset + 4);
}

/** 读 sfnt 表目录；越界或畸形的表记录直接跳过（不抛错）。 */
function readTableDirectory(buffer: Buffer, fontOffset: number): Map<string, TableRecord> {
  const numTables = u16(buffer, fontOffset + 4);
  if (numTables <= 0 || numTables > 512) throw new Error('sfnt 表数量异常');
  const tables = new Map<string, TableRecord>();
  for (let i = 0; i < numTables; i += 1) {
    const record = fontOffset + 12 + i * 16;
    const tag = readTableTag(buffer, record);
    const offset = u32(buffer, record + 8);
    const length = u32(buffer, record + 12);
    if (offset + length > buffer.length) continue;
    if (!tables.has(tag)) tables.set(tag, { offset, length });
  }
  return tables;
}

function tableData(buffer: Buffer, tables: Map<string, TableRecord>, tag: string): Buffer | null {
  const record = tables.get(tag);
  if (record === undefined) return null;
  return buffer.subarray(record.offset, record.offset + record.length);
}

/** sfnt 标准累加校验和（4 字节大端求和，末尾不足 4 字节按 0 补齐）。 */
function sfntChecksum(data: Buffer): number {
  const padded = data.length % 4 === 0 ? data : Buffer.concat([data, Buffer.alloc(4 - (data.length % 4))]);
  let sum = 0;
  for (let i = 0; i < padded.length; i += 4) {
    sum = (sum + padded.readUInt32BE(i)) % 4294967296;
  }
  return sum;
}

interface SfntTable {
  tag: string;
  data: Buffer;
}

/**
 * 组装单字体 sfnt：表按 tag 升序、偏移 4 字节对齐、checkSum 用标准累加算法，
 * 最后按规范回填 head.checkSumAdjustment（0xB1B0AFBA - 整文件校验和）。
 */
function buildSfnt(version: number, tables: SfntTable[]): Buffer {
  const sorted = [...tables].sort((a, b) => (a.tag < b.tag ? -1 : a.tag > b.tag ? 1 : 0));
  const numTables = sorted.length;

  const header = Buffer.alloc(12);
  header.writeUInt32BE(version === SFNT_TRUE ? version : SFNT_VERSION_1, 0);
  header.writeUInt16BE(numTables, 4);
  const entrySelector = Math.floor(Math.log2(numTables));
  const searchRange = 16 * 2 ** entrySelector;
  header.writeUInt16BE(searchRange, 6);
  header.writeUInt16BE(entrySelector, 8);
  header.writeUInt16BE(numTables * 16 - searchRange, 10);

  const directory = Buffer.alloc(numTables * 16);
  const chunks: Buffer[] = [header, directory];
  let dataOffset = 12 + numTables * 16;
  let headOffset = -1;

  for (const [index, table] of sorted.entries()) {
    let data = table.data;
    if (table.tag === 'head' && data.length >= 12) {
      // checkSumAdjustment 先置 0 参与 checksum 计算，最后整文件回填
      data = Buffer.from(data);
      data.writeUInt32BE(0, 8);
      headOffset = dataOffset;
    }
    const record = index * 16;
    directory.write(table.tag, record, 4, 'latin1');
    directory.writeUInt32BE(sfntChecksum(data), record + 4);
    directory.writeUInt32BE(dataOffset, record + 8);
    directory.writeUInt32BE(data.length, record + 12);
    const padding = (4 - (data.length % 4)) % 4;
    const padded = padding > 0 ? Buffer.concat([data, Buffer.alloc(padding)]) : data;
    chunks.push(padded);
    dataOffset += padded.length;
  }

  const file = Buffer.concat(chunks);
  if (headOffset >= 0) {
    file.writeUInt32BE((0xb1b0afba - sfntChecksum(file)) >>> 0, headOffset + 8);
  }
  return file;
}

/**
 * 把字体集合（.ttc）里的第 1 个字体重建成独立的单字体 sfnt。
 * FontFile2 必须是「单字体」程序，直接塞 ttcf 文件在严格阅读器里不合法。
 */
function buildStandaloneTtf(buffer: Buffer, fontOffset: number, tables: Map<string, TableRecord>): Buffer {
  const version = u32(buffer, fontOffset);
  const entries = [...tables.entries()].map(([tag, record]) => ({
    tag,
    data: buffer.subarray(record.offset, record.offset + record.length),
  }));
  return buildSfnt(version, entries);
}

/** 解析 cmap 子表（支持格式 0 / 4 / 12），返回 码点 → glyph id。 */
function parseCmapTable(cmap: Buffer): Map<number, number> {
  const result = new Map<number, number>();
  const numSubtables = u16(cmap, 2);
  const subtables: Array<{ score: number; offset: number }> = [];
  for (let i = 0; i < numSubtables; i += 1) {
    const record = 4 + i * 8;
    const platform = u16(cmap, record);
    const encoding = u16(cmap, record + 2);
    const offset = u32(cmap, record + 4);
    if (offset + 4 > cmap.length) continue;
    let score = 0;
    if (platform === 3 && encoding === 10) score = 5;
    else if (platform === 0 && (encoding === 4 || encoding === 6)) score = 4;
    else if (platform === 3 && encoding === 1) score = 3;
    else if (platform === 0) score = 2;
    else if (platform === 1 && encoding === 0) score = 1;
    if (score > 0) subtables.push({ score, offset });
  }
  subtables.sort((a, b) => b.score - a.score);

  for (const subtable of subtables) {
    if (result.size >= MAX_CMAP_ENTRIES) break;
    try {
      const format = u16(cmap, subtable.offset);
      if (format === 0) parseCmapFormat0(cmap, subtable.offset, result);
      else if (format === 4) parseCmapFormat4(cmap, subtable.offset, result);
      else if (format === 12) parseCmapFormat12(cmap, subtable.offset, result);
    } catch {
      continue;
    }
  }
  return result;
}

function parseCmapFormat0(cmap: Buffer, base: number, result: Map<number, number>): void {
  const start = base + 6;
  if (start + 256 > cmap.length) return;
  for (let code = 0; code < 256; code += 1) {
    const gid = cmap.readUInt8(start + code);
    if (gid !== 0 && !result.has(code)) result.set(code, gid);
  }
}

function parseCmapFormat4(cmap: Buffer, base: number, result: Map<number, number>): void {
  const segCountX2 = u16(cmap, base + 6);
  const segCount = segCountX2 / 2;
  if (segCount <= 0 || segCount > 65535) return;
  const endCode = base + 14;
  const startCode = endCode + segCountX2 + 2;
  const idDelta = startCode + segCountX2;
  const idRangeOffset = idDelta + segCountX2;
  for (let i = 0; i < segCount; i += 1) {
    const end = u16(cmap, endCode + i * 2);
    const start = u16(cmap, startCode + i * 2);
    const delta = i16(cmap, idDelta + i * 2);
    const rangeOffset = u16(cmap, idRangeOffset + i * 2);
    if (start > end) continue;
    for (let code = start; code <= end; code += 1) {
      if (code === 0xffff || result.size >= MAX_CMAP_ENTRIES) break;
      let gid: number;
      if (rangeOffset === 0) {
        gid = (code + delta) & 0xffff;
      } else {
        const index = idRangeOffset + i * 2 + rangeOffset + (code - start) * 2;
        if (index + 2 > cmap.length) break;
        const raw = u16(cmap, index);
        gid = raw === 0 ? 0 : (raw + delta) & 0xffff;
      }
      if (gid !== 0 && !result.has(code)) result.set(code, gid);
    }
  }
}

function parseCmapFormat12(cmap: Buffer, base: number, result: Map<number, number>): void {
  const numGroups = u32(cmap, base + 12);
  if (numGroups > MAX_CMAP_ENTRIES) return;
  for (let i = 0; i < numGroups; i += 1) {
    const group = base + 16 + i * 12;
    if (group + 12 > cmap.length) return;
    const start = u32(cmap, group);
    const end = u32(cmap, group + 4);
    const startGlyph = u32(cmap, group + 8);
    if (start > end || end - start > 0x10ffff) continue;
    for (let code = start; code <= end; code += 1) {
      if (result.size >= MAX_CMAP_ENTRIES) return;
      const gid = startGlyph + (code - start);
      if (gid !== 0 && !result.has(code)) result.set(code, gid);
    }
  }
}

/** 从 name 表取族名 / PostScript 名（优先 Windows(3) 的 UTF-16BE 记录）。 */
function parseFontNames(name: Buffer, fallback: string): { familyName: string; postScriptName: string } {
  let familyName = '';
  let postScriptName = '';
  let familyScore = -1;
  let postScriptScore = -1;
  const count = u16(name, 2);
  const stringOffset = u16(name, 4);
  for (let i = 0; i < count; i += 1) {
    const record = 6 + i * 12;
    if (record + 12 > name.length) break;
    const platform = u16(name, record);
    const nameId = u16(name, record + 6);
    const length = u16(name, record + 8);
    const offset = u16(name, record + 10);
    if (nameId !== 1 && nameId !== 6) continue;
    const start = stringOffset + offset;
    if (start + length > name.length) continue;
    const raw = name.subarray(start, start + length);
    const decoded = platform === 3 || platform === 0 ? decodeUtf16Be(raw) : raw.toString('latin1');
    const value = decoded.replace(/\u0000/g, '').trim();
    if (value === '') continue;
    const score = platform === 3 ? 3 : platform === 0 ? 2 : 1;
    if (nameId === 1 && score > familyScore) {
      familyScore = score;
      familyName = value;
    }
    if (nameId === 6 && score > postScriptScore) {
      postScriptScore = score;
      postScriptName = value;
    }
  }
  const family = familyName !== '' ? familyName : postScriptName !== '' ? postScriptName : fallback;
  const postScript = postScriptName !== '' ? postScriptName : family;
  return { familyName: family, postScriptName: postScript };
}

function decodeUtf16Be(raw: Buffer): string {
  const swapped = Buffer.alloc(raw.length);
  for (let i = 0; i + 1 < raw.length; i += 2) {
    swapped[i] = raw[i + 1];
    swapped[i + 1] = raw[i];
  }
  return swapped.toString('utf16le');
}

/** PDF 名字对象里不允许出现分隔符 / 非 ASCII，做一次保守清洗。 */
function sanitizePostScriptName(name: string): string {
  const cleaned = name.replace(/[^A-Za-z0-9+-]/g, '');
  return cleaned === '' ? 'EmbeddedFont' : cleaned.slice(0, 60);
}

/**
 * 解析一个 TrueType 字体文件（.ttf 或 .ttc 的第 1 个字体）。
 * 任何不满足「可嵌入 glyf 轮廓」条件的情况都返回 null，由调用方跳过继续找下一个。
 */
function parseTrueTypeFont(buffer: Buffer, filePath: string): EmbeddedFont | null {
  if (buffer.length < 12) return null;
  let fontOffset = 0;
  let program = buffer;
  if (u32(buffer, 0) === TTC_TAG) {
    const numFonts = u32(buffer, 8);
    if (numFonts < 1) return null;
    fontOffset = u32(buffer, 12);
    if (fontOffset + 12 > buffer.length) return null;
  }

  const tables = readTableDirectory(buffer, fontOffset);
  for (const required of REQUIRED_TABLES) {
    if (!tables.has(required)) return null;
  }
  if (readTableTag(buffer, fontOffset) === 'OTTO') return null;

  const head = tableData(buffer, tables, 'head');
  const hhea = tableData(buffer, tables, 'hhea');
  const maxp = tableData(buffer, tables, 'maxp');
  const hmtx = tableData(buffer, tables, 'hmtx');
  const cmapTable = tableData(buffer, tables, 'cmap');
  const locaTable = tableData(buffer, tables, 'loca');
  const cff = tableData(buffer, tables, CFF_TAG);
  if (head === null || hhea === null || maxp === null || hmtx === null || cmapTable === null) return null;
  if (locaTable === null || cff !== null) return null;
  if (head.length < 54 || hhea.length < 36 || maxp.length < 6) return null;

  const unitsPerEm = u16(head, 18);
  const indexToLocFormat = i16(head, 50);
  if (unitsPerEm === 0 || (indexToLocFormat !== 0 && indexToLocFormat !== 1)) return null;

  const glyphCount = u16(maxp, 4);
  if (glyphCount <= 0 || glyphCount > MAX_GLYPHS) return null;

  // loca 长度必须与 numGlyphs + 1 个偏移一致，才算真的带 glyf 轮廓
  const locaEntrySize = indexToLocFormat === 0 ? 2 : 4;
  if (locaTable.length < (glyphCount + 1) * locaEntrySize) return null;

  const numberOfHMetrics = u16(hhea, 34);
  if (numberOfHMetrics <= 0 || numberOfHMetrics > glyphCount) return null;

  const advanceWidths: number[] = new Array<number>(glyphCount);
  let lastAdvance = 0;
  for (let gid = 0; gid < glyphCount; gid += 1) {
    if (gid < numberOfHMetrics) {
      const offset = gid * 4;
      if (offset + 2 > hmtx.length) return null;
      lastAdvance = u16(hmtx, offset);
    }
    advanceWidths[gid] = lastAdvance;
  }

  const cmap = parseCmapTable(cmapTable);
  if (cmap.size === 0) return null;

  // glyph → 码点 反向表：按码点升序取第一个，保证 ToUnicode 生成确定
  const glyphToCodePoint = new Map<number, number>();
  const codePoints = [...cmap.keys()].sort((a, b) => a - b);
  for (const codePoint of codePoints) {
    const gid = cmap.get(codePoint) ?? 0;
    if (gid >= glyphCount) continue;
    if (!glyphToCodePoint.has(gid)) glyphToCodePoint.set(gid, codePoint);
  }

  if (fontOffset === 0) {
    program = buffer;
  } else {
    program = buildStandaloneTtf(buffer, fontOffset, tables);
  }

  const nameTable = tableData(buffer, tables, 'name');
  const fallbackName = path.basename(filePath).replace(/\.[^.]+$/, '');
  const names = nameTable === null ? { familyName: fallbackName, postScriptName: fallbackName } : parseFontNames(nameTable, fallbackName);

  const os2 = tableData(buffer, tables, 'OS/2');
  const ascender = i16(hhea, 4);
  const rawDescender = i16(hhea, 6);
  let capHeight = 0;
  if (os2 !== null && os2.length >= 90 && u16(os2, 0) >= 2) {
    capHeight = u16(os2, 88);
  }
  if (capHeight <= 0) capHeight = Math.round(ascender * 0.7);

  return {
    path: filePath,
    program,
    familyName: names.familyName,
    postScriptName: sanitizePostScriptName(names.postScriptName),
    glyphCount,
    unitsPerEm,
    indexToLocFormat,
    ascender,
    descender: rawDescender > 0 ? -rawDescender : rawDescender,
    capHeight,
    bbox: [i16(head, 36), i16(head, 38), i16(head, 40), i16(head, 42)],
    numberOfHMetrics,
    advanceWidths,
    cmap,
    glyphToCodePoint,
  };
}

