/** PDF 数字：最多两位小数，不用科学计数法，避免 -0。 */
function fmt(value: number): string {
  if (!Number.isFinite(value)) return '0';
  const rounded = Math.round(value * 100) / 100;
  return Object.is(rounded, -0) ? '0' : String(rounded);
}

function bufferOf(text: string): Buffer {
  return Buffer.from(text, 'latin1');
}

/** 单元格值 → 字符串（与 doc-writers 的 cellText 语义一致：null / 非有限数字 → 空串）。 */
function cellText(value: PdfCell | unknown): string {
  if (value === null || value === undefined) return '';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '';
  if (typeof value === 'string') return value;
  return '';
}

/** 该码点是否需要按「全角 / 双宽」处理（CJK、假名、谚文、全角符号等，也是换行的断点）。 */
function isWideChar(codePoint: number): boolean {
  return (
    (codePoint >= 0x1100 && codePoint <= 0x115f) ||
    (codePoint >= 0x2e80 && codePoint <= 0xa4cf) ||
    (codePoint >= 0xac00 && codePoint <= 0xd7a3) ||
    (codePoint >= 0xf900 && codePoint <= 0xfaff) ||
    (codePoint >= 0xfe30 && codePoint <= 0xfe4f) ||
    (codePoint >= 0xff00 && codePoint <= 0xff60) ||
    (codePoint >= 0xffe0 && codePoint <= 0xffe6) ||
    (codePoint >= 0x20000 && codePoint <= 0x3fffd)
  );
}

/** 文本的「字符单元数」：全角 2、其余 1（只用于表格列宽估算）。 */
function unitsOf(text: string): number {
  let units = 0;
  for (const ch of text) units += isWideChar(ch.codePointAt(0) ?? 0) ? 2 : 1;
  return units;
}

function utf16Hex(codePoint: number): string {
  if (codePoint <= 0xffff) return codePoint.toString(16).padStart(4, '0');
  const value = codePoint - 0x10000;
  const high = 0xd800 + (value >> 10);
  const low = 0xdc00 + (value & 0x3ff);
  return `${high.toString(16).padStart(4, '0')}${low.toString(16).padStart(4, '0')}`;
}

