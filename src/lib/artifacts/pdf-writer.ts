interface FontFilePlan {
  /** FontFile2 的原始（未压缩）字体程序 */
  program: Buffer;
  /** 子集化统计；整份嵌入时为 null */
  subset: SubsetStats | null;
}

/** 决定这次嵌入哪份字体程序：优先子集化，任何异常都回退成整份嵌入（宁大勿坏）。 */
function planFontFile(font: EmbeddedFont, usedGids: Set<number>, subsetFont: boolean): FontFilePlan {
  if (subsetFont) {
    try {
      const result = subsetFontProgram(font.program, usedGids);
      return { program: result.program, subset: result.stats };
    } catch {
      return { program: font.program, subset: null };
    }
  }
  return { program: font.program, subset: null };
}

/**
 * 生成 PDF。
 * - 有可用 TrueType 字体 → 嵌入并支持完整 Unicode（含中文）；默认只嵌入用到的字形（子集化）
 * - 无字体（font: null 或未发现）→ base14 Helvetica；此时若内容是纯 Latin-1 仍正常出图，
 *   并把 requiresUnicodeFont 置为 true 表示「内容有它渲染不了的字」
 */
export function writePdf(doc: PdfDocSpec, options?: WritePdfOptions): PdfWriteResult {
  const opts: WritePdfOptions = options ?? {};
  const source: PdfDocSpec = doc ?? { sections: [] };
  const footer = (source.footer ?? '').trim();
  const watermark = (opts.watermark ?? '').trim();
  const font = resolveFont(opts);

  const ctx = createContext(font);
  renderDocument(source, ctx);
  ctx.pages.push(ctx.ops);
  appendFooters(ctx, footer, watermark);

  const pageCount = ctx.pages.length;
  const contentBuffers = ctx.pages.map((ops) => bufferOf(`${ops.join('\n')}\n`));

  // 字体程序：默认子集化，任何异常都回退成整份嵌入（宁大勿坏）
  const fontFile = font === null ? null : planFontFile(font, ctx.usedGlyphs, opts.subsetFont !== false);
  const embedded = font !== null && fontFile !== null;

  const catalogRef = 1;
  const pagesRef = 2;
  const pageRef = (index: number): number => 3 + index;
  const contentRef = (index: number): number => 3 + pageCount + index;
  const fontBase = 3 + pageCount * 2;
  const infoRef = embedded ? fontBase + 5 : fontBase + 2;
  const regularFontRef = fontBase;
  const boldFontRef = embedded ? fontBase : fontBase + 1;

  const objects: Buffer[] = [];
  objects.push(bufferOf(`<< /Type /Catalog /Pages ${pagesRef} 0 R >>`));
  const kids = ctx.pages.map((_, index) => `${pageRef(index)} 0 R`).join(' ');
  objects.push(bufferOf(`<< /Type /Pages /Kids [${kids}] /Count ${pageCount} >>`));

  for (let index = 0; index < pageCount; index += 1) {
    const resources =
      `<< /Font << /F1 ${regularFontRef} 0 R /F2 ${boldFontRef} 0 R >> ` +
      `/ProcSet [/PDF /Text] >>`;
    objects.push(
      bufferOf(
        `<< /Type /Page /Parent ${pagesRef} 0 R /MediaBox [0 0 ${fmt(PAGE_WIDTH)} ${fmt(PAGE_HEIGHT)}] ` +
          `/Resources ${resources} /Contents ${contentRef(index)} 0 R >>`,
      ),
    );
  }
  for (const content of contentBuffers) objects.push(streamObject('', content));

  if (font === null || fontFile === null) {
    objects.push(base14FontObject('Helvetica', false));
    objects.push(base14FontObject('Helvetica-Bold', true));
  } else {
    // Type0 字体对象号就是 regularFontRef（fontBase），/F1 与 /F2 指向同一个 Type0 对象
    const cidRef = fontBase + 1;
    const descriptorRef = fontBase + 2;
    const fontFileRef = fontBase + 3;
    const toUnicodeRef = fontBase + 4;
    const name = font.postScriptName;
    const bbox = font.bbox.map((value) => Math.round((value * 1000) / font.unitsPerEm));

    objects.push(
      bufferOf(
        `<< /Type /Font /Subtype /Type0 /BaseFont /${name} /Encoding /Identity-H ` +
          `/DescendantFonts [${cidRef} 0 R] /ToUnicode ${toUnicodeRef} 0 R >>`,
      ),
    );
    objects.push(
      bufferOf(
        `<< /Type /Font /Subtype /CIDFontType2 /BaseFont /${name} ` +
          '/CIDSystemInfo << /Registry (Adobe) /Ordering (Identity) /Supplement 0 >> ' +
          `/FontDescriptor ${descriptorRef} 0 R /DW 1000 /W ${embeddedWidthArray(font, ctx.usedGlyphs)} ` +
          '/CIDToGIDMap /Identity >>',
      ),
    );
    objects.push(
      bufferOf(
        `<< /Type /FontDescriptor /FontName /${name} /Flags 4 ` +
          `/FontBBox [${bbox.join(' ')}] /ItalicAngle 0 /Ascent ${font.ascender} /Descent ${font.descender} ` +
          `/CapHeight ${font.capHeight} /StemV 80 /FontFile2 ${fontFileRef} 0 R >>`,
      ),
    );
    objects.push(
      streamObject(
        `/Length1 ${fontFile.program.length} /Filter /FlateDecode`,
        compressedFontProgram(font, fontFile.program),
      ),
    );
    objects.push(streamObject('', bufferOf(toUnicodeCMap(font, ctx.usedGlyphs))));
  }

  const infoParts = ['/Producer (RoveFrame AI COO PDF Writer)'];
  const title = (source.title ?? '').trim();
  if (title !== '') infoParts.push(`/Title ${pdfTextString(title)}`);
  objects.push(bufferOf(`<< ${infoParts.join(' ')} >>`));

  return {
    data: buildPdfFile(objects, catalogRef, infoRef),
    mime: PDF_MIME,
    ext: PDF_EXT,
    font: font === null ? 'helvetica' : 'embedded',
    fontPath: font === null ? undefined : font.path,
    pageCount,
    requiresUnicodeFont: font === null && needsUnicodeFont(collectText(source, watermark)),
    subset: fontFile === null ? null : fontFile.subset,
  };
}
