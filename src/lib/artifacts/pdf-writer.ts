function base14FontObject(baseFont: string, bold: boolean): Buffer {
  return bufferOf(
    `<< /Type /Font /Subtype /Type1 /BaseFont /${baseFont} /Encoding /WinAnsiEncoding ` +
      `/FirstChar 32 /LastChar 255 /Widths ${base14WidthArray(bold)} >>`,
  );
}

/** /W 稀疏宽度表：连续 glyph 合成 range，单位换算到 1/1000 em。 */
function embeddedWidthArray(font: EmbeddedFont, used: Set<number>): string {
  const gids = [...used].sort((a, b) => a - b);
  const groups: string[] = [];
  let start = -1;
  let widths: string[] = [];
  let previous = -2;
  const flush = (): void => {
    if (start >= 0) groups.push(`${start} [${widths.join(' ')}]`);
  };
  for (const gid of gids) {
    const advance = font.advanceWidths[gid];
    const width = Math.round((advance * 1000) / font.unitsPerEm);
    if (start >= 0 && gid === previous + 1) {
      widths.push(String(width));
      previous = gid;
      continue;
    }
    flush();
    start = gid;
    widths = [String(width)];
    previous = gid;
  }
  flush();
  return `[ ${groups.join(' ')} ]`;
}

/** ToUnicode CMap：glyph id → Unicode（每 100 条一个 beginbfchar 块）。 */
function toUnicodeCMap(font: EmbeddedFont, used: Set<number>): string {
  const entries: string[] = [];
  for (const gid of [...used].sort((a, b) => a - b)) {
    const codePoint = font.glyphToCodePoint.get(gid);
    if (codePoint === undefined) continue;
    entries.push(`<${utf16Hex(gid)}> <${utf16Hex(codePoint)}>`);
  }
  const blocks: string[] = [];
  for (let i = 0; i < entries.length; i += 100) {
    const slice = entries.slice(i, i + 100);
    blocks.push([`${slice.length} beginbfchar`, ...slice, 'endbfchar'].join('\n'));
  }
  if (blocks.length === 0 || entries.length === 0) blocks.push('0 beginbfchar', 'endbfchar');
  return [
    '/CIDInit /ProcSet findresource begin',
    '12 dict begin',
    'begincmap',
    '/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def',
    `/CMapName /${font.postScriptName}-UCS def`,
    '/CMapType 2 def',
    '1 begincodespacerange',
    '<0000> <FFFF>',
    'endcodespacerange',
    ...blocks,
    'endcmap',
    'CMapName currentdict /CMap defineresource pop',
    'end',
    'end',
  ].join('\n');
}

function streamObject(dict: string, data: Buffer): Buffer {
  const head = dict === '' ? `<< /Length ${data.length} >>` : `<< ${dict} /Length ${data.length} >>`;
  return Buffer.concat([bufferOf(`${head}\nstream\n`), data, bufferOf('\nendstream')]);
}

/* -------------------------------------------------------------------------- */
/* PDF 组装                                                                    */
/* -------------------------------------------------------------------------- */

function buildPdfFile(objects: Buffer[], rootRef: number, infoRef: number): Buffer {
  const chunks: Buffer[] = [];
  let offset = 0;
  const push = (data: Buffer): void => {
    chunks.push(data);
    offset += data.length;
  };

  // 二进制标记行（% 注释）让工具可靠识别这是二进制 PDF
  push(bufferOf('%PDF-1.7\n%\u00e2\u00e3\u00cf\u00d3\n'));

  const offsets: number[] = [];
  objects.forEach((body, index) => {
    offsets.push(offset);
    push(bufferOf(`${index + 1} 0 obj\n`));
    push(body);
    push(bufferOf('\nendobj\n'));
  });

  const xrefOffset = offset;
  const xref: string[] = [`xref\n0 ${objects.length + 1}\n`, '0000000000 65535 f \n'];
  for (const entry of offsets) xref.push(`${String(entry).padStart(10, '0')} 00000 n \n`);
  push(bufferOf(xref.join('')));

  push(
    bufferOf(
      `trailer\n<< /Size ${objects.length + 1} /Root ${rootRef} 0 R /Info ${infoRef} 0 R >>\n` +
        `startxref\n${xrefOffset}\n%%EOF\n`,
    ),
  );

  return Buffer.concat(chunks);
}

/** Info 字典里的文本串：纯 ASCII 用字面量，否则 UTF-16BE（带 BOM）。 */
function pdfTextString(text: string): string {
  for (const ch of text) {
    const codePoint = ch.codePointAt(0) ?? 0;
    if (codePoint < 0x20 || codePoint > 0x7e) {
      return `<feff${[...text].map((item) => utf16Hex(item.codePointAt(0) ?? 0)).join('')}>`;
    }
  }
  const escaped = text.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  return `(${escaped})`;
}

/** 收集文档里所有可见文本（用于判断是否需要 Unicode 字体）。 */
function collectText(doc: PdfDocSpec, watermark: string): string {
  const parts: string[] = [doc.title ?? '', doc.subtitle ?? '', watermark];
  const sections = Array.isArray(doc.sections) ? doc.sections : [];
  for (const section of sections) {
    parts.push(section.heading ?? '');
    for (const paragraph of Array.isArray(section.paragraphs) ? section.paragraphs : []) {
      parts.push(String(paragraph ?? ''));
    }
    for (const bullet of Array.isArray(section.bullets) ? section.bullets : []) {
      parts.push(String(bullet ?? ''));
    }
    const table = section.table;
    if (table !== undefined && table !== null) {
      parts.push(table.name ?? '');
      for (const column of Array.isArray(table.columns) ? table.columns : []) parts.push(cellText(column));
      const rows = Array.isArray(table.rows) ? table.rows : [];
      for (const row of rows) {
        if (!Array.isArray(row)) continue;
        for (const cell of row) parts.push(cellText(cell));
      }
    }
  }
  return parts.join('\n');
}

/** 解析这次渲染用哪条字体路径（null → base14）。任何失败都回落 base14，绝不抛错。 */
function resolveFont(options: WritePdfOptions): EmbeddedFont | null {
  if (options.font === null) return null;
  const info = options.font ?? discoverPdfFont(options.fontPath);
  if (info === null || info === undefined) return null;
  const fontPath = typeof info.path === 'string' ? info.path : options.fontPath;
  if (fontPath === undefined || fontPath.trim() === '') return null;
  return loadFont(fontPath);
}

