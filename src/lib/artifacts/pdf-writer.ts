/* 文本度量与编码                                                              */
/* -------------------------------------------------------------------------- */

interface LayoutContext {
  /** 嵌入字体；null 表示 base14 Helvetica */
  font: EmbeddedFont | null;
  /** 已完成页面的内容流 */
  pages: string[][];
  /** 当前页内容流 */
  ops: string[];
  /** 光标：距页面顶部的距离（pt） */
  cursor: number;
  /** 嵌入字体路径下真正写出的 glyph id */
  usedGlyphs: Set<number>;
}

/** glyph id 解析：字体里没有的码点用 .notdef（gid 0）兜底，绝不抛错。 */
function glyphFor(font: EmbeddedFont, codePoint: number): number {
  const gid = font.cmap.get(codePoint);
  if (gid === undefined || gid < 0 || gid >= font.glyphCount) return 0;
  return gid;
}

function measureText(ctx: LayoutContext, text: string, size: number, bold: boolean): number {
  const font = ctx.font;
  if (font !== null) {
    let total = 0;
    for (const ch of text) {
      total += font.advanceWidths[glyphFor(font, ch.codePointAt(0) ?? 0)];
    }
    return (total * size) / font.unitsPerEm;
  }
  let total = 0;
  for (const ch of text) total += base14Width(ch.codePointAt(0) ?? 0, bold);
  return (total * size) / 1000;
}

/**
 * 把一行文本编码成 PDF 文本对象里的字符串：
 * base14 → `(...)` 字面量（转义 `( ) \`，不可表示的字符画成 `?`）；
 * 嵌入字体 → `<0048...>`（UTF-16BE 的 glyph id 十六进制串）。
 */
function encodeText(ctx: LayoutContext, text: string): string {
  const font = ctx.font;
  if (font !== null) {
    let hex = '';
    for (const ch of text) {
      const gid = glyphFor(font, ch.codePointAt(0) ?? 0);
      ctx.usedGlyphs.add(gid);
      hex += gid.toString(16).padStart(4, '0');
    }
    return `<${hex}>`;
  }
  let out = '(';
  for (const ch of text) {
    const byte = winAnsiByte(ch.codePointAt(0) ?? 0);
    if (byte === 0x28) out += '\\(';
    else if (byte === 0x29) out += '\\)';
    else if (byte === 0x5c) out += '\\\\';
    else out += String.fromCharCode(byte);
  }
  return `${out})`;
}

/** 以 PDF 坐标（自底向上）的基线写入一行文本。 */
function pushTextLine(
  ctx: LayoutContext,
  ops: string[],
  text: string,
  x: number,
  baseline: number,
  size: number,
  bold: boolean,
  gray: number,
): void {
  if (text === '') return;
  ops.push(
    `${fmt(gray)} g BT ${bold ? '/F2' : '/F1'} ${fmt(size)} Tf 1 0 0 1 ${fmt(x)} ${fmt(baseline)} Tm ${encodeText(ctx, text)} Tj ET`,
  );
}

/** 以「距页面顶部」的位置写入一行文本（颜色必须在 BT/ET 之外设置）。 */
function drawFlowLine(
  ctx: LayoutContext,
  text: string,
  x: number,
  top: number,
  size: number,
  bold: boolean,
  gray: number,
): void {
  pushTextLine(ctx, ctx.ops, text, x, PAGE_HEIGHT - (top + size * BASELINE_RATIO), size, bold, gray);
}

/* -------------------------------------------------------------------------- */
/* 换行（按字符宽度累加）                                                      */
/* -------------------------------------------------------------------------- */

/**
 * 断行单元：CJK / 全角字符逐字成 token，拉丁词整体成 token，空白是唯一的可丢弃断点。
 * 中文没有空格，所以不能按词断行 —— 这里对全角字符逐字累加宽度。
 */
function tokenize(text: string): string[] {
  const tokens: string[] = [];
  let buffer = '';
  for (const ch of text) {
    const codePoint = ch.codePointAt(0) ?? 0;
    if (ch === ' ' || ch === '\t') {
      if (buffer !== '') {
        tokens.push(buffer);
        buffer = '';
      }
      tokens.push(SPACE_TOKEN);
      continue;
    }
    if (isWideChar(codePoint)) {
      if (buffer !== '') {
        tokens.push(buffer);
        buffer = '';
      }
      tokens.push(ch);
      continue;
    }
    buffer += ch;
  }
  if (buffer !== '') tokens.push(buffer);
  return tokens;
}

/** 单个词比整行还宽时按字符硬切（超长 URL / 无空格长串）。 */
function splitToWidth(text: string, maxWidth: number, measure: (value: string) => number): string[] {
  const chunks: string[] = [];
  let current = '';
  for (const ch of text) {
    if (current !== '' && measure(current + ch) > maxWidth) {
      chunks.push(current);
      current = ch;
      continue;
    }
    current += ch;
  }
  if (current !== '') chunks.push(current);
  return chunks;
}

/** 按可用宽度把文本折成多行；显式换行符保持。空文本返回空数组。 */
function wrapText(text: string, maxWidth: number, measure: (value: string) => number): string[] {
  const lines: string[] = [];
  const source = String(text ?? '');
  if (source === '') return lines;

  for (const paragraph of source.split(/\r\n|\r|\n/)) {
    const tokens = tokenize(paragraph);
    let line = '';
    let lineWidth = 0;
    let pendingSpace = false;
    const flush = (): void => {
      if (line !== '') lines.push(line);
      line = '';
      lineWidth = 0;
      pendingSpace = false;
    };

    for (const token of tokens) {
      if (token === SPACE_TOKEN) {
        if (line !== '') pendingSpace = true;
        continue;
      }
      const piece = pendingSpace && line !== '' ? ` ${token}` : token;
      const width = measure(piece);
      if (lineWidth + width <= maxWidth || line === '') {
        if (line === '' && width > maxWidth) {
          const chunks = splitToWidth(token, maxWidth, measure);
          for (let i = 0; i < chunks.length - 1; i += 1) lines.push(chunks[i]);
          line = chunks[chunks.length - 1];
          lineWidth = measure(line);
          pendingSpace = false;
          continue;
        }
        line += piece;
        lineWidth += width;
        pendingSpace = false;
        continue;
      }
      flush();
      if (width > maxWidth) {
        const chunks = splitToWidth(token, maxWidth, measure);
        for (let i = 0; i < chunks.length - 1; i += 1) lines.push(chunks[i]);
        line = chunks[chunks.length - 1];
        lineWidth = measure(line);
        continue;
      }
      line = token;
      lineWidth = width;
    }
    flush();
  }
  return lines;
}

