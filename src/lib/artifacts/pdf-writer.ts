function createContext(font: EmbeddedFont | null): LayoutContext {
  return { font, pages: [], ops: [], cursor: CONTENT_TOP, usedGlyphs: new Set<number>() };
}

function newPage(ctx: LayoutContext): void {
  ctx.pages.push(ctx.ops);
  ctx.ops = [];
  ctx.cursor = CONTENT_TOP;
}

/** 需要 height 高度时确保当前页放得下，否则翻页（空白新页不重复翻页）。 */
function ensureSpace(ctx: LayoutContext, height: number): void {
  if (ctx.cursor > CONTENT_TOP && ctx.cursor + height > CONTENT_BOTTOM) newPage(ctx);
}

function drawRule(ctx: LayoutContext): void {
  const y = PAGE_HEIGHT - ctx.cursor;
  ctx.ops.push(
    `${fmt(GRAY_RULE)} G ${fmt(LINE_WIDTH_THIN)} w ${fmt(MARGIN)} ${fmt(y)} m ${fmt(MARGIN + CONTENT_WIDTH)} ${fmt(y)} l S`,
  );
}

/* -------------------------------------------------------------------------- */
/* 块级渲染                                                                    */
/* -------------------------------------------------------------------------- */

function renderHeading(ctx: LayoutContext, heading: string): void {
  const measure = (value: string): number => measureText(ctx, value, SIZE_HEADING, true);
  const lines = wrapText(heading, CONTENT_WIDTH, measure);
  if (lines.length === 0) return;
  ctx.cursor += GAP_HEADING_BEFORE;
  ensureSpace(ctx, HEIGHT_HEADING + HEIGHT_BODY);
  for (const line of lines) {
    ensureSpace(ctx, HEIGHT_HEADING);
    drawFlowLine(ctx, line, MARGIN, ctx.cursor, SIZE_HEADING, true, GRAY_HEADING);
    ctx.cursor += HEIGHT_HEADING;
  }
  ctx.cursor += GAP_HEADING_AFTER;
}

function renderParagraph(ctx: LayoutContext, paragraph: string): void {
  const measure = (value: string): number => measureText(ctx, value, SIZE_BODY, false);
  const lines = wrapText(paragraph, CONTENT_WIDTH, measure);
  if (lines.length === 0) return;
  for (const line of lines) {
    ensureSpace(ctx, HEIGHT_BODY);
    drawFlowLine(ctx, line, MARGIN, ctx.cursor, SIZE_BODY, false, GRAY_BODY);
    ctx.cursor += HEIGHT_BODY;
  }
  ctx.cursor += GAP_PARAGRAPH;
}

function renderBullet(ctx: LayoutContext, bullet: string): void {
  const prefix = '• ';
  const prefixWidth = measureText(ctx, prefix, SIZE_BODY, false);
  const measure = (value: string): number => measureText(ctx, value, SIZE_BODY, false);
  const lines = wrapText(`${prefix}${bullet}`, CONTENT_WIDTH, measure);
  if (lines.length === 0) return;
  lines.forEach((line, index) => {
    ensureSpace(ctx, HEIGHT_BODY);
    drawFlowLine(ctx, line, MARGIN + (index === 0 ? 0 : prefixWidth), ctx.cursor, SIZE_BODY, false, GRAY_BODY);
    ctx.cursor += HEIGHT_BODY;
  });
  ctx.cursor += GAP_BULLET;
}

/** 按内容权重分配列宽（全角按 2 个单元估算，夹在上下限内）。 */
function columnWidths(columns: string[], rows: PdfCell[][]): number[] {
  const weights = columns.map((column, index) => {
    let maxUnits = unitsOf(column);
    for (const row of rows) maxUnits = Math.max(maxUnits, unitsOf(cellText(row[index] ?? null)));
    return Math.min(Math.max(maxUnits, COLUMN_WEIGHT_MIN), COLUMN_WEIGHT_MAX);
  });
  const total = weights.reduce((sum, weight) => sum + weight, 0);
  if (total <= 0) return columns.map(() => CONTENT_WIDTH / columns.length);
  return weights.map((weight) => (CONTENT_WIDTH * weight) / total);
}

function rowHeight(cellLines: string[][]): number {
  let maxLines = 1;
  for (const lines of cellLines) maxLines = Math.max(maxLines, lines.length);
  return maxLines * HEIGHT_TABLE + CELL_PADDING_Y * 2;
}

function drawTableRow(
  ctx: LayoutContext,
  top: number,
  widths: number[],
  cellLines: string[][],
  header: boolean,
): void {
  const height = rowHeight(cellLines);
  const bottom = PAGE_HEIGHT - top - height;
  const totalWidth = widths.reduce((sum, width) => sum + width, 0);
  if (header) {
    ctx.ops.push(
      `${fmt(GRAY_TABLE_HEADER_BG)} g ${fmt(MARGIN)} ${fmt(bottom)} ${fmt(totalWidth)} ${fmt(height)} re f`,
    );
  }
  ctx.ops.push(`${fmt(GRAY_TABLE_BORDER)} G ${fmt(LINE_WIDTH_THIN)} w`);
  let x = MARGIN;
  for (let column = 0; column < cellLines.length; column += 1) {
    const width = widths[column];
    ctx.ops.push(`${fmt(x)} ${fmt(bottom)} ${fmt(width)} ${fmt(height)} re S`);
    const lines = cellLines[column];
    for (let line = 0; line < lines.length; line += 1) {
      const baseline = bottom + height - CELL_PADDING_Y - SIZE_TABLE * BASELINE_RATIO - line * HEIGHT_TABLE;
      pushTextLine(
        ctx,
        ctx.ops,
        lines[line],
        x + CELL_PADDING_X,
        baseline,
        SIZE_TABLE,
        header,
        header ? GRAY_HEADING : GRAY_BODY,
      );
    }
    x += width;
  }
}

function renderTable(ctx: LayoutContext, table: PdfTableSpec): void {
  const columns = (Array.isArray(table.columns) ? table.columns : []).map((column) => cellText(column));
  if (columns.length === 0) return;
  const rows = Array.isArray(table.rows) ? table.rows.map((row) => (Array.isArray(row) ? row : [])) : [];

  const name = (table.name ?? '').trim();
  if (name !== '') {
    const lines = wrapText(name, CONTENT_WIDTH, (value) => measureText(ctx, value, SIZE_TABLE_NAME, true));
    for (const line of lines) {
      ensureSpace(ctx, HEIGHT_TABLE_NAME);
      drawFlowLine(ctx, line, MARGIN, ctx.cursor, SIZE_TABLE_NAME, true, GRAY_HEADING);
      ctx.cursor += HEIGHT_TABLE_NAME;
    }
    ctx.cursor += GAP_TABLE_NAME;
  }

  const widths = columnWidths(columns, rows);
  const innerWidths = widths.map((width) => Math.max(20, width - CELL_PADDING_X * 2));
  const headerLines = columns.map((column, index) =>
    wrapText(column, innerWidths[index], (value) => measureText(ctx, value, SIZE_TABLE, true)),
  );
  const bodyLines = rows.map((row) =>
    columns.map((_, index) =>
      wrapText(cellText(row[index] ?? null), innerWidths[index], (value) =>
        measureText(ctx, value, SIZE_TABLE, false),
      ),
    ),
  );

  const headerHeight = rowHeight(headerLines);
  const firstRowHeight = bodyLines.length > 0 ? rowHeight(bodyLines[0]) : 0;
  ensureSpace(ctx, headerHeight + firstRowHeight);

  drawTableRow(ctx, ctx.cursor, widths, headerLines, true);
  ctx.cursor += headerHeight;

  for (const cellLines of bodyLines) {
    const height = rowHeight(cellLines);
    if (ctx.cursor + height > CONTENT_BOTTOM) {
      newPage(ctx);
      drawTableRow(ctx, ctx.cursor, widths, headerLines, true); // 新页重复表头
      ctx.cursor += headerHeight;
    }
    drawTableRow(ctx, ctx.cursor, widths, cellLines, false);
    ctx.cursor += height;
  }
  ctx.cursor += GAP_TABLE;
}

function renderDocument(doc: PdfDocSpec, ctx: LayoutContext): void {
  const title = (doc.title ?? '').trim();
  const subtitle = (doc.subtitle ?? '').trim();

  if (title !== '') {
    const lines = wrapText(title, CONTENT_WIDTH, (value) => measureText(ctx, value, SIZE_TITLE, true));
    for (const line of lines) {
      drawFlowLine(ctx, line, MARGIN, ctx.cursor, SIZE_TITLE, true, GRAY_TITLE);
      ctx.cursor += HEIGHT_TITLE;
    }
  }
  if (subtitle !== '') {
    const lines = wrapText(subtitle, CONTENT_WIDTH, (value) => measureText(ctx, value, SIZE_SUBTITLE, false));
    for (const line of lines) {
      drawFlowLine(ctx, line, MARGIN, ctx.cursor, SIZE_SUBTITLE, false, GRAY_SUBTITLE);
      ctx.cursor += HEIGHT_SUBTITLE;
    }
  }
  if (title !== '' || subtitle !== '') {
    ctx.cursor += 6;
    drawRule(ctx);
    ctx.cursor += 14;
  }

  const sections = Array.isArray(doc.sections) ? doc.sections : [];
  for (const section of sections) {
    const heading = (section.heading ?? '').trim();
    if (heading !== '') renderHeading(ctx, heading);
    const paragraphs = Array.isArray(section.paragraphs) ? section.paragraphs : [];
    for (const paragraph of paragraphs) renderParagraph(ctx, String(paragraph ?? ''));
    const bullets = Array.isArray(section.bullets) ? section.bullets : [];
    for (const bullet of bullets) renderBullet(ctx, String(bullet ?? ''));
    if (section.table !== undefined && section.table !== null) renderTable(ctx, section.table);
  }
}

function appendFooters(ctx: LayoutContext, footer: string, watermark: string): void {
  const total = ctx.pages.length;
  ctx.pages.forEach((ops, index) => {
    if (footer !== '') {
      pushTextLine(ctx, ops, footer, MARGIN, FOOTER_BASELINE, SIZE_FOOTER, false, GRAY_FOOTER);
    }
    if (watermark !== '') {
      const width = measureText(ctx, watermark, SIZE_FOOTER, false);
      pushTextLine(ctx, ops, watermark, (PAGE_WIDTH - width) / 2, FOOTER_BASELINE, SIZE_FOOTER, false, GRAY_FOOTER);
    }
    const label = `${index + 1} / ${total}`;
    const width = measureText(ctx, label, SIZE_FOOTER, false);
    pushTextLine(ctx, ops, label, PAGE_WIDTH - MARGIN - width, FOOTER_BASELINE, SIZE_FOOTER, false, GRAY_FOOTER);
  });
}

