/**
 * 零依赖 PDF 序列化器（artifact writers）。
 *
 * 用途：AI COO 的「产物导出」链路 —— 把经营报告（PdfDocSpec：标题 / 小节 / 段落 / 列表 / 表格）
 * 序列化成真正可下载的 PDF 字节流（PdfWriteResult：data + mime + ext + 字体与页码元信息），
 * 并如实告诉调用方这次渲染用的哪条字体路径、内容里有没有它画不出来的字。
 * 本模块**只依赖 Node.js 内置模块**（node:zlib + node:fs + node:path + Buffer），不引入任何第三方依赖。
 *
 * 两条渲染路径：
 * - base14（font: null 或未发现可用字体）：/Helvetica（+ /Helvetica-Bold）+ /WinAnsiEncoding，
 *   文本用 `(...) Tj` 字面量；`(` `)` `\` 与不可打印字符按 PDF 规范转义。只覆盖 Latin-1 + WinAnsi 扩展区。
 * - 嵌入 TrueType（默认自动发现）：Type0 + /Identity-H + /CIDFontType2 + /CIDToGIDMap /Identity，
 *   文本写成 UTF-16BE 的 glyph id 十六进制串 `<0048...> Tj`，同时生成 /W 宽度表与 ToUnicode CMap
 *   （可复制 / 可搜索）；字体程序作为 FontFile2 流（FlateDecode）嵌入，**默认做子集化**（见下）。
 *
 * 实现要点：
 * - 页面是 A4（595.28 × 841.89 pt），页边距 56pt，底部预留页脚带；超过页高自动分页。
 * - 自己解析 TrueType：表目录 / head(unitsPerEm, indexToLocFormat, bbox) / hhea(numberOfHMetrics,
 *   ascender, descender) / hmtx(advanceWidth) / maxp(numGlyphs) / cmap(格式 0、4、12) / name(族名) /
 *   OS/2(sCapHeight) / glyf+loca(轮廓存在性)。字体集合 .ttc 只取第 1 个字体，并把它的表重建成
 *   独立的单字体 sfnt 再嵌入（FontFile2 必须是单字体程序）；CFF/OTF（有 `CFF ` 无 `glyf`）直接判为不可用。
 * - **字体子集化**（默认开启，`subsetFont: false` 可关）：只保留文档真正用到的字形 —— 先由 cmap 把文本映射
 *   成 gid 集合，再做**复合字形闭包**（glyf 里 numberOfContours < 0 的字形由若干 component 组成，递归收集
 *   被引用的组件，否则会出现缺笔画 / 空白字），然后重建 glyf + loca 与整个 sfnt（表按 tag 升序、4 字节对齐、
 *   标准 checkSum、head.checkSumAdjustment 按规范回填）。**不做 gid 重映射**：保留 0..maxUsedGid 的槽位，
 *   未用到的槽写成零长度空字形，于是 CIDToGIDMap /Identity、cmap、/W、ToUnicode 全部无需改动。
 *   子集化过程中任何异常都会**安全回退**成整份字体嵌入（宁大勿坏），并在结果里把 subset 置 null。
 * - 换行按**字符宽度累加**：CJK / 全角字符逐字可断，拉丁词保持整体，超长单词按字符强制切分。
 * - 表格：等宽以外的按内容权重分配列宽，单元格内文字按列宽换行，细线边框 + 表头浅灰底，
 *   跨页时表头在新页重复。
 * - 全部输出**字节确定**：不读系统时间、不用随机数，FlateDecode 只作用于确定的字节流。
 *
 * 有意为之的简化（不是 bug）：
 * - 子集不做 gid 重映射（保留槽位），因此 loca 会为未用到的槽写零长度条目；cmap 原样保留，
 *   里面仍可能有指向「超出新 numGlyphs」的 gid 的映射 —— 那些码点不会被渲染，PDF 只用我们写出的 gid；
 * - 子集里 hmtx / hhea 原样保留（读到的宽度永远在表内），post 裁成 v3.0 的 32 字节最小表，
 *   丢弃 kern / GPOS / GSUB / GDEF / gasp / hdmx / LTSH / VDMX（PDF 不需要），保留 cvt /fpgm/prep；
 * - 内容流不压缩（便于人工/脚本检查），只有 FontFile2 用 FlateDecode；
 * - 不做粗体合成：嵌入字体路径下标题只用「更大字号 + 灰度差」区分，base14 路径标题走 Helvetica-Bold；
 * - 表格数字不右对齐、不做单元格截断（超宽内容按字符换行）；
 * - Info 字典不写 CreationDate / ModDate（保证同样输入两次调用输出完全相等）。
 */

