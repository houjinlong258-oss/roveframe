function cacheFont(font: EmbeddedFont): void {
  if (FONT_CACHE.size >= FONT_CACHE_LIMIT) {
    const oldest = FONT_CACHE.keys().next();
    if (!oldest.done) FONT_CACHE.delete(oldest.value);
  }
  FONT_CACHE.set(font.path, font);
}

/** 读取 + 解析字体文件；读不到 / 解析失败返回 null（绝不抛错）。 */
function loadFont(filePath: string): EmbeddedFont | null {
  const resolved = path.resolve(filePath);
  const cached = FONT_CACHE.get(resolved);
  if (cached !== undefined) return cached;
  let font: EmbeddedFont | null = null;
  try {
    if (statSync(resolved).isFile()) {
      font = parseTrueTypeFont(readFileSync(resolved), resolved);
    }
  } catch {
    font = null;
  }
  if (font !== null) cacheFont(font);
  return font;
}

/** <cwd>/public/fonts 下的字体文件（按文件名排序，保证发现顺序确定）。 */
function projectFontCandidates(): string[] {
  const dir = path.join(process.cwd(), 'public', 'fonts');
  let names: string[] = [];
  try {
    names = readdirSync(dir).sort();
  } catch {
    return [];
  }
  return names
    .filter((name) => FONT_EXTENSIONS.includes(path.extname(name).toLowerCase()))
    .map((name) => path.join(dir, name));
}

/** 常见 CJK / 回退字体文件名（Linux 字体目录里的匹配模式）。 */
const LINUX_FONT_PATTERNS: readonly RegExp[] = [
  /^NotoSansCJK/i,
  /^NotoSerifCJK/i,
  /^NotoSansSC/i,
  /^NotoSerifSC/i,
  /^SourceHanSans/i,
  /^SourceHanSerif/i,
  /^wqy-/i,
  /^DroidSansFallback/i,
  /^ukai/i,
  /^uming/i,
];

const LINUX_FONT_ROOTS: readonly string[] = [
  '/usr/share/fonts',
  '/usr/local/share/fonts',
  '/usr/share/fonts/truetype',
  '/usr/share/fonts/opentype',
];

const MAX_FONT_SCAN_DEPTH = 4;
const MAX_FONT_SCAN_RESULTS = 60;

function scanFontDir(dir: string, depth: number, out: string[]): void {
  if (depth > MAX_FONT_SCAN_DEPTH || out.length >= MAX_FONT_SCAN_RESULTS) return;
  let entries: string[] = [];
  try {
    entries = readdirSync(dir).sort();
  } catch {
    return;
  }
  for (const entry of entries) {
    if (out.length >= MAX_FONT_SCAN_RESULTS) return;
    const full = path.join(dir, entry);
    let directory = false;
    try {
      directory = statSync(full).isDirectory();
    } catch {
      continue;
    }
    if (directory) {
      scanFontDir(full, depth + 1, out);
      continue;
    }
    if (!FONT_EXTENSIONS.includes(path.extname(entry).toLowerCase())) continue;
    if (LINUX_FONT_PATTERNS.some((pattern) => pattern.test(entry))) out.push(full);
  }
}

function linuxFontCandidates(): string[] {
  const out: string[] = [];
  for (const root of LINUX_FONT_ROOTS) scanFontDir(root, 0, out);
  return out;
}

/** 常见 Windows 字体（顺序即优先级：雅黑 → 黑体 → 宋体 → Arial 兜底）。 */
function windowsFontCandidates(): string[] {
  const dir = path.join(process.env.WINDIR ?? process.env.SystemRoot ?? 'C:\\Windows', 'Fonts');
  return ['msyh.ttc', 'simhei.ttf', 'simsun.ttc', 'arial.ttf'].map((name) => path.join(dir, name));
}

/** 按 ①explicitPath ②RF_PDF_FONT ③public/fonts ④Linux ⑤Windows 收集候选（去重、顺序稳定）。 */
function fontCandidates(explicitPath?: string): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  const add = (candidate: string | undefined): void => {
    if (candidate === undefined || candidate.trim() === '') return;
    const resolved = path.resolve(candidate.trim());
    if (seen.has(resolved)) return;
    seen.add(resolved);
    out.push(resolved);
  };
  add(explicitPath);
  add(process.env.RF_PDF_FONT);
  for (const candidate of projectFontCandidates()) add(candidate);
  for (const candidate of linuxFontCandidates()) add(candidate);
  for (const candidate of windowsFontCandidates()) add(candidate);
  return out;
}

/**
 * 发现可用的 CJK/Unicode TrueType 字体。
 * 顺序：① 参数 explicitPath ② env RF_PDF_FONT ③ <cwd>/public/fonts 下的 .ttf / .otf / .ttc
 *      ④ 常见 Linux 字体目录（NotoSansCJK*、wqy-*、DroidSansFallback* 等）
 *      ⑤ 常见 Windows 字体（msyh.ttc、simhei.ttf、simsun.ttc、arial.ttf）
 * 都找不到返回 null。读不到 / 解析失败（含 CFF/OTF）会跳过并继续找下一个，绝不抛错中断。
 */
export function discoverPdfFont(explicitPath?: string): PdfFontInfo | null {
  for (const candidate of fontCandidates(explicitPath)) {
    const font = loadFont(candidate);
    if (font !== null) {
      return { path: candidate, familyName: font.familyName, glyphCount: font.glyphCount };
    }
  }
  return null;
}

