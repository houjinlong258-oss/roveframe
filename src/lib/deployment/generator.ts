/**
 * Phase 6 — Deployment Engine
 *
 * 一句话部署：输入 { domain, environment, 服务器类型 }，生成完整部署产物包：
 *
 *   Dockerfile          — 多阶段构建（deps → build → runtime）
 *   docker-compose.yml  — app + 健康检查 + 自动重启
 *   nginx.conf          — 反向代理 + gzip + 静态缓存 +（可选）SSL
 *   deploy.sh           — 服务器端一键脚本：构建 → 迁移 → 启动 → SSL → 健康检查
 *   .env.template       — 环境变量清单
 *
 * 设计边界（务实，不过度设计）：
 *   - 本模块只生成产物与脚本，不直接 SSH 到用户服务器执行
 *   - SSL 使用 certbot --nginx 半自动（脚本内含命令，需人工确认邮箱）
 *   - 所有生成内容确定性输出（无随机、无时间戳），可测试、可 diff
 */

export interface DeploymentConfig {
  /** 域名，如 app.example.com；留空则跳过 SSL/域名配置（仅 IP 访问） */
  domain?: string;
  /** 运行端口（容器内部） */
  port: number;
  /** 环境：production | staging */
  environment: 'production' | 'staging';
  /** 镜像名 */
  imageName: string;
  /** 健康检查路径 */
  healthPath: string;
  /** certbot 邮箱（启用 SSL 时建议提供） */
  sslEmail?: string;
}

export interface DeploymentArtifact {
  /** 相对路径，如 'Dockerfile' */
  path: string;
  content: string;
  /** 是否需要可执行权限（deploy.sh） */
  executable?: boolean;
}

export interface DeploymentPlan {
  config: DeploymentConfig;
  artifacts: DeploymentArtifact[];
  /** 人类可读的执行步骤 */
  steps: string[];
}

export const DEFAULT_DEPLOYMENT_CONFIG: DeploymentConfig = {
  port: 5000,
  environment: 'production',
  imageName: 'roveframe-ai-business-os',
  healthPath: '/en',
};

// ---------------------------------------------------------------------------
// 校验
// ---------------------------------------------------------------------------

export function validateDeploymentConfig(
  input: Partial<DeploymentConfig>
): { valid: boolean; errors: string[]; config: DeploymentConfig } {
  const errors: string[] = [];
  const config: DeploymentConfig = { ...DEFAULT_DEPLOYMENT_CONFIG, ...input };

  if (config.domain !== undefined && config.domain !== '') {
    if (!/^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$/i.test(config.domain)) {
      errors.push(`invalid domain: ${config.domain}`);
    }
  }
  if (!Number.isInteger(config.port) || config.port < 1 || config.port > 65535) {
    errors.push(`invalid port: ${config.port}`);
  }
  if (config.environment !== 'production' && config.environment !== 'staging') {
    errors.push(`invalid environment: ${config.environment}`);
  }
  if (!/^[a-z0-9][a-z0-9._/-]{0,127}$/.test(config.imageName)) {
    errors.push(`invalid imageName: ${config.imageName}`);
  }
  if (!config.healthPath.startsWith('/')) {
    errors.push('healthPath must start with /');
  }
  if (config.sslEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(config.sslEmail)) {
    errors.push(`invalid sslEmail: ${config.sslEmail}`);
  }

  return { valid: errors.length === 0, errors, config };
}

