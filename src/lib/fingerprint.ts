import { createHash } from 'node:crypto';

/**
 * 下单幂等指纹的统一实现。
 *
 * ## 为什么是哈希，不是原始字符串
 *
 * 指纹的用途只有一个：判断"同一个幂等键，两次请求的内容是否相同"。
 * 它是个**比较键**，不是给人看的数据。因此没有理由存原文 —— 而存原文有两个真实代价：
 *
 * 1. **会超列宽，且是实测发生过的**。`orders.idempotency_fingerprint` 是
 *    varchar(128)。外卖指纹原文形如
 *      `<商品uuid> x<qty>,…|<小计>|<配送费>|<地址>|<电话>`
 *    两个商品 uuid 就占 77 字符；加金额与一个正常的纽约地址后实测 **147 字符** →
 *    插入抛 22001 → 接口 **500**。也就是说：**两件商品的外卖单在真实地址下下不成功**。
 *    哈希后恒为 64 字符，与商品数、地址长度都无关。
 *
 * 2. **会把顾客的地址与电话明文写进一个语义上不该有 PII 的列**。
 *    `idempotency_fingerprint` 不是业务字段，却被用来承载收货地址与电话 ——
 *    任何能读 orders 表的人都看得到，而它本不该在那里。哈希后不含原文。
 *
 * ## 为什么用原始字符串拼输入再哈希，而不是改成结构化哈希
 *
 * 拼接规则属于**既有契约**（顺序、分隔符会影响结果），改了会让"同内容必须同指纹"
 * 的既有断言失效。所以只在最后加一层哈希，拼接逻辑原样保留 ——
 * 改动面最小，语义不变。
 *
 * ## 兼容性（重要）
 *
 * 库里已有的旧指纹是原文。新算法算出的哈希与它对不上，因此**旧幂等键的重放会得到
 * 409 `idempotency_key_conflict` 而不是幂等命中**。这是**fail-closed**：
 * 宁可让旧键报冲突（用户换一个键即可），也不能因为算法变更而把两张不同的单
 * 误判成同一张。旧指纹的寿命本就只有下单重试那几分钟。
 */
export function hashFingerprint(input: string): string {
  return createHash('sha256').update(input).digest('hex');
}

/** 指纹列的宽度上限。任何新指纹都必须不超过它 —— 由守卫测试钉住。 */
export const FINGERPRINT_MAX_LENGTH = 128;

/** sha256 十六进制长度。列宽若被改小到这个值以下，指纹就会写不进去。 */
export const FINGERPRINT_LENGTH = 64;
