describe('writePdf / 嵌入 TrueType', () => {
  const font = discoverPdfFont();

  test('含中文 + 发现字体：Type0 / Identity-H / FontFile2 / ToUnicode 齐全', (t) => {
    if (font === null) {
      t.skip('本机未发现可用 TrueType 字体（discoverPdfFont() === null）');
      return;
    }
    const result = writePdf(chineseDoc(), { font });
    assert.equal(result.font, 'embedded');
    assert.equal(result.fontPath, font.path);
    assert.equal(result.requiresUnicodeFont, false, '嵌入字体后不应再要求调用方降级');
    assert.ok(result.pageCount >= 1);
    assertPdfStructure(result.data);

    assert.ok(result.data.includes('/Type0'), '嵌入路径必须声明 /Type0');
    assert.ok(result.data.includes('/Identity-H'), '嵌入路径必须用 /Identity-H 编码');
    assert.ok(result.data.includes('/CIDFontType2'), '嵌入路径必须是 /CIDFontType2');
    assert.ok(result.data.includes('/CIDToGIDMap /Identity'), 'CID 到 GID 必须是 Identity 映射');
    assert.ok(result.data.includes('/FontFile2'), '字体程序必须以 /FontFile2 内嵌');
    assert.ok(result.data.includes('/FlateDecode'), 'FontFile2 应使用 FlateDecode 压缩');
    assert.ok(result.data.includes('/ToUnicode'), '必须生成 ToUnicode CMap（可复制 / 可搜索）');
    assert.ok(result.data.includes('beginbfchar'), 'ToUnicode CMap 必须含 beginbfchar 映射');
    assert.ok(/\/W \[\s*\d+ \[/.test(asText(result.data)), '/W 必须是稀疏形式 [ gid [w...] ... ]');
    assert.ok(/<[0-9a-f]{4,}> Tj/.test(asText(result.data)), '文本必须写成 glyph id 十六进制串');
  });

  test('discoverPdfFont 的结果自洽，且 explicitPath 优先', (t) => {
    if (font === null) {
      t.skip('本机未发现可用 TrueType 字体');
      return;
    }
    assert.ok(font.glyphCount > 0, 'glyphCount 必须大于 0');
    assert.equal(typeof font.path, 'string');
    assert.ok(font.path.length > 0);
    assert.ok(font.familyName.trim().length > 0, 'familyName 不能为空');
    assert.ok(existsSync(font.path), '返回的路径必须真实存在');

    const explicit = discoverPdfFont(font.path);
    assert.ok(explicit !== null, '显式传入可用字体路径必须命中');
    assert.equal(explicit.path, font.path);
    assert.equal(explicit.glyphCount, font.glyphCount);

    const bogus = discoverPdfFont('Z:\\roveframe-no-such-dir\\no-such-font.ttf');
    if (bogus !== null) {
      assert.ok(existsSync(bogus.path), '显式路径失败后应继续找系统字体，而不是返回假路径');
    }
  });

  test('嵌入路径下 emoji / 控制字符 / 缺字不会崩（回落 .notdef）', (t) => {
    if (font === null) {
      t.skip('本机未发现可用 TrueType 字体');
      return;
    }
    const doc: PdfDocSpec = {
      title: '边界字符测试 🎉 \u0000\u0007',
      sections: [{ paragraphs: ['中文 + emoji 🚀 + 罕见字 𠮷 + 控制符 \u0001', 'x'.repeat(400)] }],
    };
    const result = writePdf(doc, { font });
    assert.equal(result.font, 'embedded');
    assertPdfStructure(result.data);
    assert.ok(result.pageCount >= 1);
  });
});

