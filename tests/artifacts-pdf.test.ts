/** 文本型断言用 latin1 解码（PDF 里的对象体是 ASCII / Latin-1）。 */
function asText(data: Buffer): string {
  return data.toString('latin1');
}

/** 从页对象字典里读 /Count（Pages 对象在文件头部，只解码前 64KB 足够）。 */
function declaredPageCount(data: Buffer): number {
  const head = asText(data.subarray(0, Math.min(data.length, 65536)));
  const match = /\/Type \/Pages[^>]*\/Count (\d+)/.exec(head);
  assert.ok(match !== null, 'PDF 必须包含带 /Count 的 /Type /Pages 对象');
  return Number.parseInt(match[1], 10);
}

/**
 * 结构校验：%PDF 头 / xref 表 / trailer / startxref / %%EOF，
 * 并且**逐条验证 xref 偏移确实指向对应对象头**（比只看关键字强得多）。
 */
function assertPdfStructure(data: Buffer): void {
  const text = asText(data);

  assert.ok(text.startsWith('%PDF-1.'), 'PDF 必须以 %PDF-1.x 开头');
  assert.ok(text.includes('xref'), 'PDF 必须含 xref 表');
  assert.ok(text.includes('trailer'), 'PDF 必须含 trailer');
  assert.ok(text.trimEnd().endsWith('%%EOF'), 'PDF 必须以 %%EOF 结尾');

  const startxrefIndex = text.lastIndexOf('startxref');
  assert.ok(startxrefIndex > 0, 'PDF 必须含 startxref');
  const offsetToken = text.slice(startxrefIndex + 'startxref'.length).trim().split(/\s+/)[0];
  const startxref = Number.parseInt(offsetToken, 10);
  assert.ok(Number.isInteger(startxref) && startxref > 0, 'startxref 必须是正整数偏移');
  assert.equal(text.slice(startxref, startxref + 4), 'xref', 'startxref 指向的偏移处必须是 xref');

  const header = /^xref\n0 (\d+)\n/.exec(text.slice(startxref));
  assert.ok(header !== null, 'xref 表头必须是 "xref\\n0 N\\n"');
  const count = Number.parseInt(header[1], 10);
  assert.ok(count >= 2, 'xref 至少应包含空闲条目 + 若干对象');
  const tableStart = startxref + header[0].length;
  for (let index = 1; index < count; index += 1) {
    const entry = text.slice(tableStart + index * 20, tableStart + index * 20 + 20);
    assert.equal(entry.length, 20, `xref 第 ${index} 条必须是固定 20 字节`);
    // 20 字节 = 10 位偏移 + 空格 + 5 位代数 + 空格 + 'n' + 2 字节行结束符
    assert.match(entry, /^\d{10} \d{5} n [\r\n]$/, `xref 第 ${index} 条格式不合法`);
    const objectOffset = Number.parseInt(entry.slice(0, 10), 10);
    const expected = `${index} 0 obj`;
    assert.equal(
      text.slice(objectOffset, objectOffset + expected.length),
      expected,
      `xref 第 ${index} 条的偏移没有指向对象头`,
    );
  }

  const trailer = text.slice(text.lastIndexOf('trailer'), text.lastIndexOf('trailer') + 200);
  assert.match(trailer, /\/Size \d+/, 'trailer 必须含 /Size');
  assert.match(trailer, /\/Root \d+ 0 R/, 'trailer 必须含 /Root');
}

