describe('needsUnicodeFont', () => {
  test('ASCII 与 Latin-1 文本不需要 Unicode 字体', () => {
    assert.equal(needsUnicodeFont(''), false);
    assert.equal(needsUnicodeFont('Revenue $12,480 - up 8.3%'), false);
    assert.equal(needsUnicodeFont('café résumé naïve'), false);
    assert.equal(needsUnicodeFont('“smart quotes” – dash • bullet €'), false);
    assert.equal(needsUnicodeFont('line one\nline two\ttabbed'), false);
  });

  test('CJK / emoji / 其他符号需要 Unicode 字体', () => {
    assert.equal(needsUnicodeFont('中文'), true);
    assert.equal(needsUnicodeFont('四川人家'), true);
    assert.equal(needsUnicodeFont('日本語のテキスト'), true);
    assert.equal(needsUnicodeFont('한국어'), true);
    assert.equal(needsUnicodeFont('🎉 emoji'), true);
    assert.equal(needsUnicodeFont('箭头 → 与全角付费'), true);
    assert.equal(needsUnicodeFont('mixed 中英文 text'), true);
  });

  test('C0 控制字符属于 ASCII 区，不算「缺字体」（排版时会被清掉）', () => {
    assert.equal(needsUnicodeFont('\u0000\u0001\u0007'), false);
    assert.equal(needsUnicodeFont('control \u001f char'), false);
  });
});

