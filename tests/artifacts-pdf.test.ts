describe('writePdf / base14（font: null）', () => {
  test('纯 ASCII 内容生成成功且不需要 Unicode 字体', () => {
    const result = writePdf(asciiDoc(), { font: null });
    assert.equal(result.mime, 'application/pdf');
    assert.equal(result.ext, 'pdf');
    assert.equal(result.font, 'helvetica');
    assert.equal(result.fontPath, undefined);
    assert.equal(result.requiresUnicodeFont, false);
    assert.equal(result.pageCount, 1);
    assert.ok(result.data.length > 1000, 'PDF 不该是空壳');
    assertPdfStructure(result.data);

    const text = asText(result.data);
    assert.ok(text.includes('/Type1'), 'base14 路径必须用 /Type1 字体');
    assert.ok(text.includes('/Helvetica-Bold'), 'base14 路径的标题必须用 Helvetica-Bold');
    assert.ok(text.includes('/WinAnsiEncoding'), 'base14 路径必须声明 /WinAnsiEncoding');
    assert.ok(text.includes('(Weekly Business Report) Tj'), '文本必须以字面量写进内容流');
  });

  test('含中文但无字体：不抛错，requiresUnicodeFont 为 true', () => {
    const result = writePdf(chineseDoc(), { font: null });
    assert.equal(result.font, 'helvetica');
    assert.equal(result.requiresUnicodeFont, true);
    assert.equal(result.pageCount, 1);
    assertPdfStructure(result.data);
    assert.equal(declaredPageCount(result.data), result.pageCount);
  });

  test('font 指向不存在的文件时回落 base14（不抛错）', () => {
    const missing = 'Z:\\roveframe-no-such-dir\\no-such-font.ttf';
    const result = writePdf(chineseDoc(), {
      font: { path: missing, familyName: 'Nope', glyphCount: 1 },
    });
    assert.equal(result.font, 'helvetica');
    assert.equal(result.fontPath, undefined);
    assert.equal(result.requiresUnicodeFont, true);
    assertPdfStructure(result.data);
  });

  test('`(` `)` `\\` 与其它不可表示字符不破坏 PDF 结构', () => {
    const doc: PdfDocSpec = {
      title: 'Escaping (test) \\ backslash',
      sections: [
        {
          paragraphs: ['parens (a) and \\ backslash', 'deep ((())) and \\\\ done', 'control \u0001\u0002 char'],
        },
      ],
    };
    const result = writePdf(doc, { font: null });
    assert.equal(result.font, 'helvetica');
    assert.equal(result.requiresUnicodeFont, false);
    assertPdfStructure(result.data);

    const text = asText(result.data);
    assert.ok(
      text.includes('(parens \\(a\\) and \\\\ backslash) Tj'),
      '括号与反斜杠必须被转义成 \\( \\) \\\\',
    );
    assert.ok(text.includes('(deep \\(\\(\\(\\)\\)\\) and \\\\\\\\ done) Tj'), '连续括号同样要转义');
    // 两个相邻控制字符是同一个断行 token，因此输出 "control ?? char"（各自回落成 ?）
    assert.ok(text.includes('(control ?? char) Tj'), '不可打印字符应折叠为 ? 而不是写进内容流');
  });
});

