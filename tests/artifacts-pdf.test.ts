describe('writePdf / 结构与分页', () => {
  test('空文档不抛错且至少一页', () => {
    const result = writePdf({ sections: [] }, { font: null });
    assert.equal(result.pageCount, 1);
    assert.equal(result.font, 'helvetica');
    assert.equal(result.requiresUnicodeFont, false);
    assertPdfStructure(result.data);
    assert.equal(declaredPageCount(result.data), 1);
  });

  test('只有标题 / 只有页脚也不抛错', () => {
    const onlyTitle = writePdf({ title: 'Title only', sections: [] }, { font: null });
    const onlyFooter = writePdf({ sections: [], footer: 'Generated by RoveFrame AI COO' }, { font: null });
    assert.equal(onlyTitle.pageCount, 1);
    assert.equal(onlyFooter.pageCount, 1);
    assertPdfStructure(onlyTitle.data);
    assertPdfStructure(onlyFooter.data);
  });

  test('300 段长文本自动分页，且 /Count 与 pageCount 一致', () => {
    const paragraphs = Array.from(
      { length: 300 },
      (_, index) => `第 ${index + 1} 条经营分析：本周该品类营业额环比上涨 8.3%，建议下周继续加大投放力度并关注库存周转天数。`,
    );
    const result = writePdf({ title: '长报告', sections: [{ heading: '明细', paragraphs }] }, { font: null });
    assert.ok(result.pageCount > 1, `300 段长文本应产生多页，实际 ${result.pageCount}`);
    assertPdfStructure(result.data);
    assert.equal(declaredPageCount(result.data), result.pageCount);
  });

  test('中文长段落按字宽换行（中文没有空格，不能按词断行）', () => {
    const paragraph = '经营分析'.repeat(150); // 600 个汉字，远超一行
    const result = writePdf({ sections: [{ paragraphs: [paragraph] }] }, { font: null });
    const text = asText(result.data);
    const lineCount = text.match(/\) Tj/g)?.length ?? 0;
    assert.ok(lineCount >= 5, `600 个汉字应折成多行，实际只有 ${lineCount} 行`);
    // 每行长度必须受页面宽度约束（内容宽 483.28pt，11pt 的 '?' 宽 6.116pt）
    for (const match of text.matchAll(/\((\?+)\) Tj/g)) {
      assert.ok(match[1].length <= 80, `单行 ${match[1].length} 个字符，超出行宽约束`);
    }
  });

  test('超长无空格单词被强制切分而不溢出', () => {
    // 'W' 在 Helvetica 里是 944/1000 em：11pt → 10.384pt；内容宽 483.28pt → 每行正好 46 个
    const charsPerLine = 46;
    const result = writePdf({ sections: [{ paragraphs: ['W'.repeat(charsPerLine * 30)] }] }, { font: null });
    assertPdfStructure(result.data);
    const lines = [...asText(result.data).matchAll(/\((W+)\) Tj/g)].map((match) => match[1].length);
    assert.equal(lines.length, 30, '1380 个连续字符应被切成 30 行');
    assert.ok(
      lines.every((length) => length === charsPerLine),
      `每行都应是 ${charsPerLine} 个字符，实际 ${lines.join(',')}`,
    );
  });
});

