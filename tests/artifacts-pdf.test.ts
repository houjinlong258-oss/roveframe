interface SfntTableRecord {
  tag: string;
  checksum: number;
  offset: number;
  length: number;
}

interface TestSfnt {
  data: Buffer;
  records: SfntTableRecord[];
  numGlyphs: number;
  indexToLocFormat: number;
  /** numGlyphs + 1 个 glyf 偏移（已按 format 换算成字节） */
  loca: number[];
  glyfOffset: number;
  glyfLength: number;
}

/** 逐位独立的 sfnt 累加校验和（末尾不足 4 字节按 0 补齐）。 */
function testChecksum(data: Buffer): number {
  const padded = data.length % 4 === 0 ? data : Buffer.concat([data, Buffer.alloc(4 - (data.length % 4))]);
  let sum = 0;
  for (let i = 0; i < padded.length; i += 4) sum = (sum + padded.readUInt32BE(i)) % 4294967296;
  return sum;
}

function parseTestSfnt(data: Buffer): TestSfnt {
  assert.equal(data.readUInt32BE(0), 0x00010000, '字体程序必须是 sfnt version 1.0');
  const numTables = data.readUInt16BE(4);
  const records: SfntTableRecord[] = [];
  const byTag = new Map<string, SfntTableRecord>();
  for (let i = 0; i < numTables; i += 1) {
    const record = 12 + i * 16;
    const entry: SfntTableRecord = {
      tag: data.toString('latin1', record, record + 4),
      checksum: data.readUInt32BE(record + 4),
      offset: data.readUInt32BE(record + 8),
      length: data.readUInt32BE(record + 12),
    };
    records.push(entry);
    byTag.set(entry.tag, entry);
  }
  const lookup = (tag: string): SfntTableRecord => {
    const entry = byTag.get(tag);
    assert.ok(entry !== undefined, `字体程序缺少 ${tag} 表`);
    return entry;
  };
  const head = lookup('head');
  const maxp = lookup('maxp');
  const loca = lookup('loca');
  const glyf = lookup('glyf');
  const numGlyphs = data.readUInt16BE(maxp.offset + 4);
  const indexToLocFormat = data.readInt16BE(head.offset + 50);
  assert.ok(indexToLocFormat === 0 || indexToLocFormat === 1, 'indexToLocFormat 必须是 0 或 1');
  const entrySize = indexToLocFormat === 0 ? 2 : 4;
  assert.equal(loca.length, (numGlyphs + 1) * entrySize, 'loca 条目数必须 = numGlyphs + 1');
  const locaOffsets: number[] = [];
  for (let gid = 0; gid <= numGlyphs; gid += 1) {
    locaOffsets.push(
      indexToLocFormat === 0 ? data.readUInt16BE(loca.offset + gid * 2) * 2 : data.readUInt32BE(loca.offset + gid * 4),
    );
  }
  return { data, records, numGlyphs, indexToLocFormat, loca: locaOffsets, glyfOffset: glyf.offset, glyfLength: glyf.length };
}

/** 从 PDF 里取出 /FontFile2 流并解 FlateDecode。 */
function extractFontFile2(pdf: Buffer): Buffer {
  const marker = pdf.indexOf('/FontFile2');
  assert.ok(marker > 0, 'PDF 必须含 /FontFile2');
  const dictStart = pdf.indexOf('/Length1 ', marker);
  assert.ok(dictStart > marker, '/FontFile2 对象必须带 /Length1');
  const dict = pdf.toString('latin1', dictStart, dictStart + 240);
  const match = /\/Length1 (\d+) \/Filter \/FlateDecode \/Length (\d+) >>\nstream\n/.exec(dict);
  assert.ok(match !== null, 'FontFile2 字典格式不符合预期');
  const streamStart = dictStart + match.index + match[0].length;
  const raw = inflateSync(pdf.subarray(streamStart, streamStart + Number.parseInt(match[2], 10)));
  assert.equal(raw.length, Number.parseInt(match[1], 10), '/Length1 必须等于解压后的字体程序长度');
  return raw;
}

function parseSubset(pdf: Buffer): TestSfnt {
  return parseTestSfnt(extractFontFile2(pdf));
}

/** 子集里非空（有轮廓数据）的 gid 集合。 */
function presentGlyphs(sfnt: TestSfnt): Set<number> {
  const present = new Set<number>();
  for (let gid = 0; gid < sfnt.numGlyphs; gid += 1) {
    if (sfnt.loca[gid + 1] > sfnt.loca[gid]) present.add(gid);
  }
  return present;
}

function glyphIsComposite(sfnt: TestSfnt, gid: number): boolean {
  if (sfnt.loca[gid + 1] <= sfnt.loca[gid]) return false;
  return sfnt.data.readInt16BE(sfnt.glyfOffset + sfnt.loca[gid]) < 0;
}

/** 复合字形的 component gid 列表（按 flag 累加 component 长度，直到 MORE_COMPONENTS 清零）。 */
function glyphComponents(sfnt: TestSfnt, gid: number): number[] {
  const start = sfnt.glyfOffset + sfnt.loca[gid];
  const end = sfnt.glyfOffset + Math.min(sfnt.loca[gid + 1], sfnt.glyfLength);
  const components: number[] = [];
  let offset = start + 10;
  while (offset + 4 <= end) {
    const flags = sfnt.data.readUInt16BE(offset);
    components.push(sfnt.data.readUInt16BE(offset + 2));
    offset += 4;
    offset += (flags & 0x0001) !== 0 ? 4 : 2;
    if ((flags & 0x0008) !== 0) offset += 2;
    else if ((flags & 0x0040) !== 0) offset += 4;
    else if ((flags & 0x0080) !== 0) offset += 8;
    if ((flags & 0x0020) === 0) break;
  }
  return components;
}

/** 内容流里写出的 glyph id（嵌入路径的 `<0048...> Tj`；只看字体对象之前的部分，避开二进制流误匹配）。 */
function usedGlyphsFromPdf(pdf: Buffer): Set<number> {
  const fontSection = pdf.indexOf('/Type0');
  const text = pdf.toString('latin1', 0, fontSection > 0 ? fontSection : pdf.length);
  const used = new Set<number>();
  for (const match of text.matchAll(/<([0-9a-f]+)> Tj/g)) {
    for (let i = 0; i + 4 <= match[1].length; i += 4) {
      used.add(Number.parseInt(match[1].slice(i, i + 4), 16));
    }
  }
  assert.ok(used.size > 0, '内容流里必须能读到 glyph id');
  return used;
}

/** 子集 sfnt 结构自校验：tag 升序 / 偏移对齐 / 每表 checkSum / 整文件 checkSum / loca 与 maxp、head 一致。 */
function assertSubsetSfntStructure(sfnt: TestSfnt): void {
  const tags = sfnt.records.map((record) => record.tag);
  assert.deepEqual(tags, [...tags].sort(), 'sfnt 表必须按 tag 升序排列');
  assert.ok(tags.includes('glyf') && tags.includes('loca') && tags.includes('maxp') && tags.includes('head'));

  for (const record of sfnt.records) {
    assert.equal(record.offset % 4, 0, `${record.tag} 表偏移必须 4 字节对齐`);
    assert.ok(record.offset + record.length <= sfnt.data.length, `${record.tag} 表超出文件范围`);
    const tableData = Buffer.from(sfnt.data.subarray(record.offset, record.offset + record.length));
    if (record.tag === 'head') tableData.writeUInt32BE(0, 8); // head 的 checkSum 按 checkSumAdjustment = 0 计算
    assert.equal(testChecksum(tableData), record.checksum, `${record.tag} 表 checkSum 不匹配`);
  }

  assert.equal(testChecksum(sfnt.data), 0xb1b0afba, '整文件 checkSum 必须等于 0xB1B0AFBA（checkSumAdjustment 正确回填）');

  for (let gid = 0; gid < sfnt.numGlyphs; gid += 1) {
    assert.ok(sfnt.loca[gid + 1] >= sfnt.loca[gid], `loca[${gid}] 必须单调不减`);
  }
  assert.equal(sfnt.loca[sfnt.numGlyphs], sfnt.glyfLength, 'loca 最后一项必须等于 glyf 表长度');
  assert.equal(sfnt.glyfLength % 2, 0, 'short loca 要求 glyf 长度为偶数');
}

